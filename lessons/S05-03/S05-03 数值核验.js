// 读取《S05-03 课文 v1 候选.md》与《S05-03 图与交互方案 v1 候选.md》，重算课文与图中的每个关键数字，
// 并断言这些数字确实出现在文件里。模型数字尽量用两种互不依赖的算法得到（逐个年景枚举 / 闭式公式；协方差 / beta 换算）。
// 论文报告的统计量（F、I 组）来自原文，不重算其数据，只核对其内部算术并断言课文写法与来源登记一致。
// 不依赖网络，不依赖 scratchpad。
'use strict';
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const lesson = fs.readFileSync(path.join(dir, 'S05-03 课文 v1 候选.md'), 'utf8').replace(/\r/g, '');
const figs = fs.readFileSync(path.join(dir, 'S05-03 图与交互方案 v1 候选.md'), 'utf8').replace(/\r/g, '');

let pass = 0, fail = 0;
function ok(name, cond, note) {
  if (cond) pass++; else { fail++; console.log('失败 ' + name + (note ? '：' + note : '')); }
}
function near(name, x, y, tol) { ok(name, Math.abs(x - y) <= (tol === undefined ? 0.005 : tol), x + ' vs ' + y); }
function inL(s) { ok('课文含「' + s + '」', lesson.includes(s)); }
function inF(s) { ok('图方案含「' + s + '」', figs.includes(s)); }
const f2 = x => (Math.round(x * 100 + 1e-9) / 100).toFixed(2);
const f1 = x => (Math.round(x * 10 + 1e-9) / 10).toFixed(1);

// ===== A 组：开场回顾与竞价直觉（第 1、2 节） =====
const sp0 = Math.sqrt(0.25 * 900 + 0.25 * 900); // S05-02：各半、互不相干
ok('A 21.21', f2(sp0) === '21.21'); inL('约 21.21%'); inL('平均回报却还是 10%');
near('A 多承担约 8.79 个百分点（将近 9）', 30 - sp0, 8.79, 0.01); inL('将近 9 个百分点');
const rf = 4, payoff = 108;
near('A 买家一出价 $100', payoff / 1.08, 100, 1e-9); inL('$108 ÷ 1.08 = $100');
ok('A 买家二出价 $103.85', f2(payoff / (1 + rf / 100)) === '103.85'); inL('$108 ÷ 1.04，约 $103.85');
near('A 按 $100 成交时期望回报 8%', (payoff / 100 - 1) * 100, 8, 1e-9);
near('A 按 $103.85 成交时期望回报约 4%', (payoff / 103.85 - 1) * 100, 4, 0.01);
inL('期望回报只剩 4%'); inL('比国债多 4 个百分点，也就是 8% 的期望回报');

// ===== B 组：方差拆分（第 3 节、图 1） =====
const sm = 20, vm = sm * sm, s = 30, v = s * s;
const stocks = { 北岭: 1.4, 超市: 0.5 };
const sysV = b => b * b * vm, ownV = b => v - sysV(b);
near('B 北岭 跟着市场 784', sysV(1.4), 784, 1e-9); near('B 北岭 自己 116', ownV(1.4), 116, 1e-9);
near('B 超市 跟着市场 100', sysV(0.5), 100, 1e-9); near('B 超市 自己 800', ownV(0.5), 800, 1e-9);
ok('B 北岭 自己 10.77%', f2(Math.sqrt(116)) === '10.77'); ok('B 超市 自己 28.28%', f2(Math.sqrt(800)) === '28.28');
near('B 超市 跟着市场 10%', Math.sqrt(100), 10, 1e-12);
// 第二种算法：由相关系数 ρ = β σm / σ 算共同部分 ρ²σ²
for (const [k, b] of Object.entries(stocks)) {
  const rho = b * sm / s;
  near('B ' + k + ' ρ²σ² = β²σm²', rho * rho * v, sysV(b), 1e-9);
  near('B ' + k + ' β = ρ × σ / σm', rho * s / sm, b, 1e-12);
}
ok('B 北岭相关系数约 0.93', (1.4 * 20 / 30).toFixed(2) === '0.93'); ok('B 超市相关系数约 0.33', (0.5 * 20 / 30).toFixed(2) === '0.33');
inL('1.4² × 400 = 784'); inL('0.5² × 400 = 100'); inL('| 116 |'); inL('| 800 |'); inL('约 0.93'); inL('约 0.33');
inL('自己的部分只有约 10.77%'); inL('约 28.28%，跟着市场的部分只有 10%');
inF('784'); inF('116'); inF('800'); inF('约 10.77%'); inF('约 28.28%'); inF('约 0.93'); inF('约 0.33');

// ===== C 组：证券市场线（第 4 节、图 2、小题 2） =====
const mrp = 5, capm = b => rf + b * mrp;
near('C 北岭 11%', capm(1.4), 11, 1e-12); near('C 超市 6.5%', capm(0.5), 6.5, 1e-12);
near('C 差 4.5 个百分点', capm(1.4) - capm(0.5), 4.5, 1e-12);
inL('4% + 1.4 × 5% = 11%'); inL('4% + 0.5 × 5% = 6.5%'); inL('差了 4.5 个百分点'); inL('市场组合的期望回报就是 9%');
const btn = [[0, '4%'], [0.5, '6.5%'], [1, '9%'], [1.4, '11%'], [2, '14%']];
for (const [b, t] of btn) { ok('C β=' + b + ' → ' + t, (capm(b) + '%') === t); }
inL('4%、6.5%、9%、11%、14%'); inF('β = 0 → 4%'); inF('β = 0.5 → 6.5%'); inF('β = 1 → 9%'); inF('β = 1.4 → 11%'); inF('β = 2 → 14%');
inL('（0，4%）经过（1，9%）到（2，14%）');
// 小题 2
near('C 小题 2 正确 10%', capm(1.2), 10, 1e-12); inL('4% + 1.2 × 5% = 10%');
near('C 小题 2 B 14.8%', rf + 1.2 * 9, 14.8, 1e-12); inL('B. 14.8%');
near('C 小题 2 C 6%', rf + 0.4 * mrp, 6, 1e-12); inL('C. 6%');
// 股票甲 β = 0 与竞价例子一致
near('C β=0 的股票甲期望回报 = 无风险利率', capm(0), rf, 1e-12);

// ===== D 组：两种年景（第 5 节） =====
const states = [{ p: .5, ex: 25 }, { p: .5, ex: -15 }];
const mEx = states.reduce((a, x) => a + x.p * x.ex, 0);
const sdM = Math.sqrt(states.reduce((a, x) => a + x.p * (x.ex - mEx) ** 2, 0));
near('D 市场平均超额 5', mEx, 5, 1e-12); near('D 市场波动率 20', sdM, 20, 1e-12);
near('D 好年景市场 +29%', rf + 25, 29, 1e-12); near('D 坏年景市场 −11%', rf - 15, -11, 1e-12);
const row = b => states.map(x => rf + b * x.ex);
ok('D 北岭 39 / −17', row(1.4).map(x => +x.toFixed(6)).join(',') === '39,-17');
ok('D 超市 16.5 / −3.5', row(0.5).map(x => +x.toFixed(6)).join(',') === '16.5,-3.5');
near('D 枚举平均 = CAPM（北岭）', row(1.4).reduce((a, x) => a + x / 2, 0), capm(1.4), 1e-12);
near('D 枚举平均 = CAPM（超市）', row(0.5).reduce((a, x) => a + x / 2, 0), capm(0.5), 1e-12);
near('D 市场平均 9%', (29 - 11) / 2, 9, 1e-12);
inL('4% + 1.4 × 25% = +39%'); inL('4% + 0.5 × 25% = +16.5%'); inL('4% − 1.4 × 15% = −17%'); inL('4% − 0.5 × 15% = −3.5%');
inL('回报是 29%，比无风险利率多 25 个百分点'); inL('市场组合是 −11%，比无风险利率少 15 个百分点'); inL('波动率正好是 20%');
inL('北岭电池跌 17%，超市股只跌 3.5%');

// ===== E 组：事后平均与标准误差（第 5 节；S0503-R06 第 39、44 页） =====
const years = 2003 - 1927 + 1;
ok('E 1927—2003 共 77 年', years === 77); inL('七十七年'); inL('21.0 ÷ √77');
near('E 21.0 ÷ √77 ≈ 2.4（与论文报告的标准误差一致）', 21.0 / Math.sqrt(years), 2.4, 0.01);
ok('E 8.3 − 2 × 2.4 = 3.5', f1(8.3 - 2 * 2.4) === '3.5'); ok('E 8.3 + 2 × 2.4 = 13.1', f1(8.3 + 2 * 2.4) === '13.1');
inL('每年平均多赚 8.3 个百分点'); inL('标准差约 21.0 个百分点'); inL('标准误差是 2.4 个百分点'); inL('在 3.5% 到 13.1% 之间');

// ===== F 组：图 3 的论文统计量（S0503-R06 第 33、42 页） =====
for (const t of ['8.3%', '11.1%', '16.8%', '13.7%', '11.8%', '10.1%', '11.2%', '16.7%']) { ok('F 课文图 3 含 ' + t, lesson.includes(t)); ok('F 图方案含 ' + t, figs.includes(t)); }
near('F 低 beta 组多赚约 2.8（将近 3）', 11.1 - 8.3, 2.8, 1e-9); inL('多赚了将近 3 个百分点');
near('F 高 beta 组少赚约 3.1（约 3）', 16.8 - 13.7, 3.1, 1e-9); inL('少赚了约 3 个百分点');
near('F 账面市值比两端相差 6.6', 16.7 - 10.1, 6.6, 1e-9); inF('差了 6.6 个百分点');
// 论文第 42 页的内部算术：无风险利率 5.8%；由预测值与 beta 反推的市场溢价约 5.5
const rfB = 5.8;
near('F 由 11.8 与 β 1.09 反推溢价 ≈ 5.5', (11.8 - rfB) / 1.09, 5.5, 0.01);
near('F 由 11.2 与 β 0.98 反推溢价 ≈ 5.5', (11.2 - rfB) / 0.98, 5.5, 0.02);
near('F 要解释 10.1% 需 β ≈ 0.78', (10.1 - rfB) / 5.5, 0.78, 0.005);
near('F 要解释 16.7% 需 β ≈ 1.98', (16.7 - rfB) / 5.5, 1.98, 0.005);
near('F 论文文字中的「11.3」= 5.8 + 5.5（市场回报，而非溢价；课文不用此数）', rfB + 5.5, 11.3, 1e-9);
ok('F 课文不出现 11.3', !lesson.includes('11.3'));
inL('beta 只有 0.98'); inL('从 1.09 降到 0.78'); inL('从 0.98 升到 1.98'); inL('应该是 11.8% 和 11.2%');
inL('1928 年到 2003 年'); inL('1963 年到 2003 年');

// ===== G 组：两因子算例与小题 4（第 8 节） =====
const vp = 3, two = (b, h) => rf + b * mrp + h * vp;
near('G 股票乙 11.4%', two(1.0, 0.8), 11.4, 1e-12); near('G 股票丙 8.4%', two(1.0, -0.2), 8.4, 1e-12);
near('G CAPM 都是 9%', capm(1.0), 9, 1e-12); near('G 差 3 个百分点', two(1.0, 0.8) - two(1.0, -0.2), 3, 1e-12);
inL('4% + 5% + 0.8 × 3% = 11.4%'); inL('4% + 5% − 0.2 × 3% = 8.4%'); inL('差了 3 个百分点');
near('G 小题 4 正确 11.5%', two(1.2, 0.5), 11.5, 1e-12); inL('4% + 1.2 × 5% + 0.5 × 3% = 11.5%');
near('G 小题 4 A 10%', capm(1.2), 10, 1e-12); near('G 小题 4 C 12.5%', rf + 1.2 * 5 + 0.5 * 5, 12.5, 1e-12);
near('G 小题 4 D 7.5%', 1.2 * 5 + 0.5 * 3, 7.5, 1e-12);
inL('A. 10%'); inL('B. 11.5%'); inL('C. 12.5%'); inL('D. 7.5%');

// ===== H 组：引用已完成课的数字（S04-06 戴尔案，S0406-R01） =====
inL('都是 3.31%'); inL('一个取 1.35，一个取 1.31'); inL('一个取 5.50%，一个取 6.41%');

// ===== I 组：其他论文统计量（与来源登记一致） =====
inL('1931 年到 1965 年这 35 年'); ok('I 1931—1965 为 35 年', 1965 - 1931 + 1 === 35);
inL('1963 年到 1990 年'); inL('8.3%、3.6% 和 5.0%'); inL('21.0%、14.6% 和 14.2%');
inL('1963 年 7 月到 2012 年 12 月'); inL('20 个国家的股市');
inL('平均每月跌 8.6%，成长股组合跌 10.3%'); inL('1968 年到 1990 年'); inL('过去 3 到 12 个月');

// ===== J 组：禁用内容、图方案一致性、小题与结构 =====
const L = lesson.split('\n');
const body = L.slice(L.findIndex(l => /^---\s*$/.test(l)) + 1).join('\n');
ok('J 正文无核验标记与开发痕迹', !/[☐◐✔]|TODO|待 ?PO|待核|待定|占位|北岭银行|轧空|盘口|扫货|吃单/.test(body));
ok('J 正文不点名「联合假设」', !/联合假设/.test(body));
ok('J 正文不出现期权定价细节', !/二叉树|Black.?Scholes|delta/i.test(body));
ok('J 课文图 1–3 都在图方案里', [1, 2, 3].every(n => lesson.includes('【图 ' + n + '】') && figs.includes('图 ' + n)));
ok('J 只有 3 张图', (body.match(/【图 \d】/g) || []).length === 3);
ok('J 四道小题', (body.match(/【小题 \d】/g) || []).length === 4);
ok('J 图方案不含指数序列', !/标普 ?500|S&P 500|纳斯达克指数|MSCI|罗素|道琼斯/.test(figs));
ok('J 承接 S05-02 的问题', body.includes('分散不掉的那部分风险，市场会不会为它付钱？'));
ok('J 首次出现「市场暴露」「因子暴露」', body.includes('**市场暴露**（market exposure）') && body.includes('**因子暴露**（factor exposure）'));
ok('J 每个「假设」的模型数字都标了假设', (body.match(/\*\*假设\*\*/g) || []).length >= 4);

console.log('通过 ' + pass + '，失败 ' + fail);
if (fail) process.exit(1);
