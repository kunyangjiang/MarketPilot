// 重算值按 dp 位四舍五入后应等于 want（字符串）；want 必须出现在课文（以及可选的图方案）里
function num(id, got, want, dp, o = {}) {
  ok(id + ' 重算', neg(fx(got, dp)) === want, `重算 ${got} → ${neg(fx(got, dp))}，课文写 ${want}`);
  const t = o.text || want;
  if (o.lesson !== false) inL(id, t);
  if (o.fig) inF(id, o.figText || t);
}
