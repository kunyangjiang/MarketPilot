function ytm(cfs, price) { let lo = -0.5, hi = 1; for (let i = 0; i < 200; i++) { const m = (lo + hi) / 2; const p = cfs.reduce((s, c, k) => s + c / Math.pow(1 + m, k + 1), 0); if (p > price) lo = m; else hi = m; } return (lo + hi) / 2; }

