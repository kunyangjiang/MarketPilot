// S03-05 数值核验：node "lessons/S03-05/S03-05 数值核验.js"
// 读取《S03-05 课文 v1 候选.md》与《S03-05 图与交互方案 v1 候选.md》，对每个关键数字既重算、又断言它出现在文件里。
// 不依赖网络或临时目录。原始数据（USGS、外汇局、论文数字）按核验记录中的来源抄录于此。
'use strict';
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const lesson = fs.readFileSync(path.join(dir, 'S03-05 课文 v1 候选.md'), 'utf8').replace(/\r/g, '');
const figs = fs.readFileSync(path.join(dir, 'S03-05 图与交互方案 v1 候选.md'), 'utf8').replace(/\r/g, '');

let pass = 0, fail = 0;
function ok(id, desc, cond) { if (cond) pass++; else { fail++; console.log('失败 ' + id + '：' + desc); } }
const near = (a, b, tol) => Math.abs(a - b) <= (tol === undefined ? 0.005 : tol);
const inL = s => lesson.includes(s);
const inF = s => figs.includes(s);
function num(id, desc, value, expected, tol, strs, where) {
  ok(id, desc + ' 重算 ' + value + ' ≈ ' + expected, near(value, expected, tol));
  for (const s of strs) ok(id, desc + ' 出现「' + s + '」于' + (where === 'F' ? '图方案' : where === 'LF' ? '课文与图方案' : '课文'),
    where === 'F' ? inF(s) : where === 'LF' ? (inL(s) && inF(s)) : inL(s));
}

// A 回报拆分（课文第 5 节；图 3）
const cost = 4000;
num('A1', '房产份额回报', (160 + (4080 - 4000)) / cost * 100, 6.00, 1e-9, ['$160', '$4,080', '6.00%'], 'LF');
num('A2', '房产现金流部分', 160 / cost * 100, 4.00, 1e-9, ['4 个百分点', '4.00%']);
num('A3', '房产价格部分', 80 / cost * 100, 2.00, 1e-9, ['2 个百分点']);
num('A4', '黄金上涨情景', (4200 - 4000 - 20) / cost * 100, 4.50, 1e-9, ['$4,200', '$20', '4.50%'], 'LF');
num('A5', '黄金不变情景', (0 - 20) / cost * 100, -0.50, 1e-9, ['−0.50%'], 'LF');
num('A6', '原油换月（贵 $0.30）每次', (60 / 60.30 - 1) * 100, -0.4975, 0.0001, ['$60.30', '0.50%']);
num('A7', '原油换月（贵）12 次', (Math.pow(60 / 60.30, 12) - 1) * 100, -5.81, 0.005, ['5.81%'], 'LF');
num('A8', '原油换月（便宜）12 次', (Math.pow(60 / 59.70, 12) - 1) * 100, 6.20, 0.005, ['6.20%'], 'LF');
num('A9', '炼油思想实验价差', 63 - 60, 3, 0, ['$63', '$3', '$60'], 'LF');

// B 图 3 表格各段（图方案）
num('B1', '房产现金流段', 160 / cost * 100, 4.00, 1e-9, ['+4.00%'], 'F');
num('B2', '房产价格段', 80 / cost * 100, 2.00, 1e-9, ['+2.00%'], 'F');
num('B3', '黄金价格段', 200 / cost * 100, 5.00, 1e-9, ['+5.00%'], 'F');
num('B4', '黄金持有成本段', -20 / cost * 100, -0.50, 1e-9, ['−0.50%'], 'F');
num('B5', '期货展期（贵）', (Math.pow(60 / 60.30, 12) - 1) * 100, -5.81, 0.005, ['−5.81%'], 'F');
num('B6', '期货展期（便宜）', (Math.pow(60 / 59.70, 12) - 1) * 100, 6.20, 0.005, ['+6.20%'], 'F');
num('B7', '房产合计 = 现金流 + 价格', 4.00 + 2.00, 6.00, 1e-9, ['6.00%'], 'F');
num('B8', '黄金合计 = 价格 + 成本', 5.00 - 0.50, 4.50, 1e-9, ['4.50%'], 'F');
num('B9', '换月价差', 60.30 - 60, 0.30, 1e-9, ['$0.30'], 'LF');
num('B10', '本金', 4000, 4000, 0, ['$4,000'], 'LF');

// C 1934 年金元（课文第 6 节）
const pureOld = 25.8 * 0.9, pureNew = (15 + 5 / 21) * 0.9;
num('C1', '旧金元纯金格令', pureOld, 23.22, 1e-9, ['25.8', '23.22', '480']);
num('C2', '旧每盎司美元', 480 / pureOld, 20.67, 0.005, ['$20.67']);
num('C3', '新金元纯金格令', pureNew, 13.714, 0.0005, ['15 又 5/21', '13.714']);
num('C4', '新每盎司美元', 480 / pureNew, 35.00, 1e-9, ['$35.00']);
num('C5', '美元价上升', (480 / pureNew) / (480 / pureOld) * 100 - 100, 69.3, 0.05, ['69%']);
num('C6', '新旧含金比', (15 + 5 / 21) / 25.8 * 100, 59.06, 0.005, ['59%']);
num('C7', '一美元少换的黄金', 100 - (15 + 5 / 21) / 25.8 * 100, 40.94, 0.005, ['41%']);
ok('C8', '行政令数字出现于课文', inL('$10,000') && inL('十年') && inL('$100') && inL('1933 年 5 月 1 日'));

// D 美国地质调查局（课文第 3、7 节）
const shares = { 首饰: 40, 金条: 24, 央行: 21, 金币: 7, 电子: 7, 其他: 1 };
num('D1', '消费构成合计', Object.values(shares).reduce((a, b) => a + b, 0), 100, 0,
  ['首饰约占 40%', '实物金条约占 24%', '约占 21%', '纪念章约占 7%', '电子电气约占 7%', '其他约 1%']);
num('D2', '央行约五分之一', 21 / 100, 0.2, 0.011, ['约五分之一']);
num('D3', '2025 / 2024 年均金价', (3300 / 2388 - 1) * 100, 38.19, 0.005, ['$2,388', '$3,300', '38%']);
const DS = { 1980: 19700000, 2001: 8750000 }, OZ_PER_T = 32150.7;
num('D4', '1980 年单位价值 $/盎司', DS[1980] / OZ_PER_T, 612.7, 0.05, ['$613']);
num('D5', '2001 年单位价值 $/盎司', DS[2001] / OZ_PER_T, 272.2, 0.05, ['$272']);
ok('D6', '1980→2001 跌掉一半以上', DS[2001] / DS[1980] < 0.5 && inL('一半以上'));

// E 机会成本与论文数字（课文第 7 节）
num('E1', 'TIPS 2.86% 的一年实际收益', 4000 * 0.0286, 114.40, 1e-9, ['2.86%', '$114.40']);
ok('E2', 'Erb & Harvey 相关系数出现于课文', inL('−0.82') && inL('−0.31') && inL('1997') && inL('2012'));

// F 中国对照（外汇局官方储备资产表）
const sep = { q: 7747, v: 3235.17 }, oct = { q: 7830, v: 3064.11 };
num('F1', '黄金数量增加（万盎司）', oct.q - sep.q, 83, 0, ['7,747', '7,830', '83 万盎司']);
num('F2', '美元金额减少（亿美元）', sep.v - oct.v, 171.06, 1e-6, ['3,235.17', '3,064.11', '171.06']);

console.log('通过 ' + pass + '，失败 ' + fail);
if (fail) process.exit(1);
