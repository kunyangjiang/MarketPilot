// 每个期望值都是手写的独立数字（四舍五入到课文要用的位数），不由被检验的公式生成。
// 来源：CPI 指数 = BLS CPI-U，U.S. city average，all items，不季调（1982-84=100），经 FRED CPIAUCNS 下载并与
// BLS 2026-10-14 新闻稿核对（2026-09 = 336.940）；TB3MS 经 FRED；房贷 = FHFA MIRS 表 9（第 3 轮起，不用 PMMS）；
// FDIC 全国平均利率 2026-11-16。
'use strict';
const assert = require('node:assert');

const out = [];
function near(id, label, value, expect, tol) {
  assert.ok(Number.isFinite(value) && Math.abs(value - expect) <= tol,
    id + ' ' + label + ': got ' + value + ', expected ' + expect);
  out.push(id + '\t' + label + '\t' + value.toFixed(6) + ' ≈ ' + expect);
}
function is(id, label, cond) { assert.ok(cond, id + ' ' + label); out.push(id + '\t' + label + '\t成立'); }
const P = 0.005;   // 到 0.01 个百分点的容差
const D = 0.005;   // 到「分」的容差

const approx = (i, pi) => i - pi;                                  // 费雪近似式 r ≈ i − π（百分数）
const exact = (i, pi) => ((1 + i / 100) / (1 + pi / 100) - 1) * 100; // 精确式 (1+i) = (1+r)(1+π)
const yoy = (now, before) => (now / before - 1) * 100;               // 12 个月变化（百分数）

// ---------- 一、CPI 指数（BLS CPI-U，不季调，1982-84=100） ----------
const CPI = {
  '1971-12': 41.1, '1972-12': 42.5, '1978-12': 67.7, '1979-12': 76.7, '1980-12': 86.3,
  '2025-09': 324.800, '2026-09': 336.940,
  '2025-10': null,          // BLS 未发布：2025 年拨款中断期间未采集数据
  '2026-10': 337.511,
};
near('C1', '2026 年 9 月同比（不季调）', yoy(CPI['2026-09'], CPI['2025-09']), 3.74, P);
near('C1', 'BLS 新闻稿公布值（一位小数）', Math.round(yoy(CPI['2026-09'], CPI['2025-09']) * 10) / 10, 3.7, 1e-9);
is('C2', '2026 年 10 月没有官方同比：2025 年 10 月指数缺失', CPI['2025-10'] === null);
near('C3', '1979 年 12 月同比', yoy(CPI['1979-12'], CPI['1978-12']), 13.29, P);
near('C3', '1980 年 12 月同比', yoy(CPI['1980-12'], CPI['1979-12']), 12.52, P);
near('C3', '1972 年 12 月同比', yoy(CPI['1972-12'], CPI['1971-12']), 3.41, P);

// ---------- 二、教学主线：小林的 $10,000 存一年，存款利率 3% ----------
near('B1', '3% 对 3%：年末美元', 10000 * 1.03, 10300.00, D);
near('B1', '3% 对 3%：精确实际回报', exact(3, 3), 0.00, P);
near('B1', '3% 对 3%：按年初价格算的购买力', 10000 * 1.03 / 1.03, 10000.00, D);
near('B2', '3% 对 6%：购买力', 10000 * 1.03 / 1.06, 9716.98, D);
near('B2', '3% 对 6%：精确', exact(3, 6), -2.83, P);
near('B3', '3% 对 1%：购买力', 10000 * 1.03 / 1.01, 10198.02, D);
near('B3', '3% 对 1%：精确', exact(3, 1), 1.98, P);

// ---------- 三、费雪关系：近似式与精确式 ----------
near('F1', '5% 对 3%：近似', approx(5, 3), 2.00, P);
near('F1', '5% 对 3%：精确', exact(5, 3), 1.94, P);
// 图 F2：名义利率固定 5%，横轴通胀，纵轴「近似 − 精确」（百分点）
near('F2', 'π=0', approx(5, 0) - exact(5, 0), 0.00, P);
near('F2', 'π=2', approx(5, 2) - exact(5, 2), 0.06, P);
near('F2', 'π=5（两式都为 0）', approx(5, 5) - exact(5, 5), 0.00, P);
near('F2', 'π=10', approx(5, 10) - exact(5, 10), -0.45, P);
near('F2', 'π=20', approx(5, 20) - exact(5, 20), -2.50, P);
// 恒等式：近似 − 精确 = (i − π)·π / (1 + π)
for (const pi of [1, 3, 8, 13.29, 20]) {
  const lhs = approx(5, pi) - exact(5, pi), rhs = (5 - pi) * (pi / 100) / (1 + pi / 100);
  near('F2', '误差恒等式 π=' + pi, lhs - rhs, 0, 1e-9);
}

// ---------- 四、历史场景（Regulation Q） ----------
// 第 2 轮更正：商业银行储蓄存款上限 1979-07-01 才由 5% 提到 5.25%（Richmond Fed, Tucker 1980）。
// 推荐用 1980 年：全年上限 5.25%（至 1984-01-01 才升到 5.50%，Gilbert 表 1）。
near('H1', '1980 储户 5.25%：近似', approx(5.25, yoy(CPI['1980-12'], CPI['1979-12'])), -7.27, P);
near('H1', '1980 储户 5.25%：精确', exact(5.25, yoy(CPI['1980-12'], CPI['1979-12'])), -6.46, P);
// 备选 1979（只有下半年是 5.25%，上半年是 5%）：两种上限分别算，课文不能只写 5.25%
near('H2', '1979 储户按 5.25%：近似', approx(5.25, yoy(CPI['1979-12'], CPI['1978-12'])), -8.04, P);
near('H2', '1979 储户按 5.25%：精确', exact(5.25, yoy(CPI['1979-12'], CPI['1978-12'])), -7.10, P);
near('H2', '1979 储户按 5%：精确', exact(5, yoy(CPI['1979-12'], CPI['1978-12'])), -7.32, P);
// 第 3 轮：房贷改用 FHFA MIRS 表 9（前身为联邦住房贷款银行委员会 FHLBB 的调查；常规单户住房贷款、全部住房、
// 年度全国平均）1972 年：合同利率 7.40%，含费用摊销的有效利率 7.53%，平均期限 26.1 年。不再使用 Freddie Mac PMMS。
// 「固定利率」是教学假设：MIRS 1972 年未报告可调利率占比（N/A*）。
// 第 4 轮：7.40% 是 MIRS「1972 年全年平均」合同利率（全部期限，平均 26.1 年），不是 30 年固定利率；
// PO 提到的 7.38%（年均）与 7.40%（7、8 月）是 Freddie Mac PMMS，不上网站。这里各年数字只是「那一年」的实际成本，
// 30 年贷款最终的实际成本取决于整个还款期的通胀，不能用某一年的 CPI 代表。
// 首期费用 0.83%（占贷款额）与有效利率 7.53% 均为 MIRS 表 9 原值，不由本脚本推算。
const MIRS72 = { contract: 7.40, effective: 7.53 };
near('H3', '名义借款成本（合同利率）', MIRS72.contract, 7.40, 1e-9);
near('H3', '名义借款成本（有效利率，含费用）', MIRS72.effective, 7.53, 1e-9);
near('H3', '1972 年那一年的实际成本（合同利率，只是那一年）', exact(MIRS72.contract, yoy(CPI['1972-12'], CPI['1971-12'])), 3.86, P);
near('H3', '同一张贷款 1979 年那一年的实际成本', exact(MIRS72.contract, yoy(CPI['1979-12'], CPI['1978-12'])), -5.20, P);
near('H3', '同一张贷款 1980 年那一年的实际成本', exact(MIRS72.contract, yoy(CPI['1980-12'], CPI['1979-12'])), -4.55, P);
near('H3', '1980 年那一年，按含费用的有效利率', exact(MIRS72.effective, yoy(CPI['1980-12'], CPI['1979-12'])), -4.43, P);
// 第 3 轮：1980 年开场的口径——CPI-U 不季调，1980-12 指数 ÷ 1979-12 指数
const ratio80 = CPI['1980-12'] / CPI['1979-12'];
near('H5', '指数比 86.3 ÷ 76.7', ratio80, 1.125163, 1e-6);
near('H5', '实际回报 (1+i)/指数比 − 1，i = 5.25% 按单利年率', ((1 + 0.0525) / ratio80 - 1) * 100, -6.46, P);
// 课文采用的简化：把 5.25% 当作全年实际得到的年回报，不计年内复利。
// 敏感性（只在核验里，不进课文）：若按日复利付足 5.25% 的年率，年化约 5.39%；Reg Q 的复利规则未核
const effDaily = (Math.pow(1 + 0.0525 / 365, 365) - 1) * 100;
near('H5', '5.25% 按日复利的年化收益（假设）', effDaily, 5.39, P);
near('H5', '按日复利情形的实际回报（假设）', ((1 + effDaily / 100) / ratio80 - 1) * 100, -6.33, P);
// 第 4 轮 ✔：储贷协会与互助储蓄银行储蓄存款上限 5½%，自 1979-07-01 生效，1980-12-31 仍有效
// （联储《Annual Statistical Digest 1980》表 8；同表商业银行 5¼%，自 1979-07-01，此前 5%，自 1973-07-01）
near('H6', '储蓄机构上限 5.50% 的实际回报', exact(5.50, yoy(CPI['1980-12'], CPI['1979-12'])), -6.24, P);
// 能买国库券的人（TB3MS 年内月均值的平均，只作对照，不是持有到期回报）
near('H4', '1979 国库券平均利率的精确实际值', exact(10.0692, yoy(CPI['1979-12'], CPI['1978-12'])), -2.85, P);
near('H4', '1980 国库券平均利率的精确实际值', exact(11.4342, yoy(CPI['1980-12'], CPI['1979-12'])), -0.96, P);
is('H4', '1980 年国库券持有者比存折储户少亏', exact(11.4342, 12.52) > exact(5.25, 12.52));

// ---------- 五、意外通胀的再分配（图 F4：一笔合同两个人） ----------
// 借 $10,000，一年，固定名义利率 5%；签约时双方预期通胀 2%，事后通胀 6%
near('R1', '到期还款（美元）', 10000 * 1.05, 10500.00, D);
near('R1', '按预期 2% 折回购买力', 10500 / 1.02, 10294.12, D);
near('R1', '按实际 6% 折回购买力', 10500 / 1.06, 9905.66, D);
near('R1', '储户少得 = 借款人少还（购买力）', 10500 / 1.02 - 10500 / 1.06, 388.46, D);
near('R1', '事前实际利率', exact(5, 2), 2.94, P);
near('R1', '事后实际利率', exact(5, 6), -0.94, P);
near('R2', '若通胀如期 2%：储户少得的购买力为 0', 10500 / 1.02 - 10500 / 1.02, 0.00, D);

// ---------- 六、回到今天：平均储蓄账户与最新官方同比 ----------
// FDIC 全国平均储蓄 0.39%、12 个月 CD 1.81%（2026-11-16）；CPI 用 2026 年 9 月同比（最新官方 12 个月变化）
const pi26 = yoy(CPI['2026-09'], CPI['2025-09']);
near('N1', '储蓄 0.39%：精确（用 3.7377%）', exact(0.39, pi26), -3.23, P);
near('N1', '储蓄 0.39%：近似（用公布值 3.7%）', approx(0.39, 3.7), -3.31, P);
near('N1', '12 个月 CD 1.81%：精确', exact(1.81, pi26), -1.86, P);
// 注意：日期不同步须在课文写明——利率是 2026-11-16 的，通胀是截至 2026 年 9 月的 12 个月（BLS 2026-10-14 发布）

// ---------- 七、课文 v1 候选新增（2026-11-18） ----------
// 开场：假想储户 1980 年元旦存 $1,000，按 5.25% 全年、不计年内复利
near('K1', '年底账上', 1000 * 1.0525, 1052.50, D);
near('K1', '年初 $1,000 的东西年底要花', 1000 * ratio80, 1125.16, D);
near('K1', '按年初价格折算的购买力（课文「约 $935」）', 1000 * 1.0525 / ratio80, 935.42, D);
near('K1', '购买力少了（%）', (1 - 1.0525 / ratio80) * 100, 6.46, P);
near('K1', '年底一个 $100 篮子的价格', 100 * ratio80, 112.52, D);
near('K1', '$1,052.50 能买的篮子数', 1052.50 / (100 * ratio80), 9.35, D);
is('K1', '上限 5% 的时期：1973-07-01 至 1979-07-01 为六年', 1979 - 1973 === 6);
// 第二节：篮子数（年初 $100 一个篮子，$10,300 能买几个）
near('K2', '通胀 1%：篮子数', 10300 / 101, 101.98, D);
near('K2', '通胀 3%：篮子数', 10300 / 103, 100.00, D);
near('K2', '通胀 6%：篮子数', 10300 / 106, 97.17, D);
near('Q1', '小题 1：2% 对 4% 的精确实际回报', exact(2, 4), -1.92, P);
is('Q1', '小题 1：符号为负', exact(2, 4) < 0);
// 第三节：近似与精确表（名义 5%）
for (const [pi, a, e] of [[0, 5.00, 5.00], [2, 3.00, 2.94], [5, 0.00, 0.00], [10, -5.00, -4.55], [20, -15.00, -12.50]]) {
  near('K3', 'π=' + pi + ' 近似', approx(5, pi), a, P);
  near('K3', 'π=' + pi + ' 精确', exact(5, pi), e, P);
}
near('K3', '1980 近似与精确之差（百分点，课文「约 0.8」）', exact(5.25, yoy(CPI['1980-12'], CPI['1979-12'])) - approx(5.25, yoy(CPI['1980-12'], CPI['1979-12'])), 0.81, 0.01);
near('Q2', '小题 2：近似', approx(5, 20), -15, P);
near('Q2', '小题 2：精确', exact(5, 20), -12.5, P);
// 第四节：CPI 指数比
near('K4', '336.940 ÷ 324.800', CPI['2026-09'] / CPI['2025-09'], 1.0374, 0.00005);
near('K4', '86.3 ÷ 76.7', ratio80, 1.1252, 0.00005);
// 第五节：意外低（1%）
near('R3', '通胀 1%：$10,500 按年初价格', 10500 / 1.01, 10396.04, D);
near('R3', '比预期多得的购买力', 10500 / 1.01 - 10500 / 1.02, 101.92, D);
// 1972→1980 物价水平
near('K5', '1980-12 ÷ 1972-12（「两倍多」）', CPI['1980-12'] / CPI['1972-12'], 2.03, 0.005);
near('K5', '1980 年一美元相当于 1972 年的购买力', CPI['1972-12'] / CPI['1980-12'], 0.49, 0.005);
is('K5', '「不到一半」', CPI['1972-12'] / CPI['1980-12'] < 0.5);
is('K5', '平均期限 26.1 年写作「约 26 年」', Math.round(26.1) === 26);
// 第六节：1980 年三个月国库券（FRED TB3MS，联储 H.15，月均，银行贴现率口径）
const TB80 = [12.00, 12.86, 15.20, 13.20, 8.58, 7.07, 8.06, 9.13, 10.27, 11.62, 13.73, 15.49];
near('K6', '1980 各月平均', TB80.reduce((a, b) => a + b) / 12, 11.43, P);
near('K6', '与 H4 所用 11.4342 一致', TB80.reduce((a, b) => a + b) / 12, 11.4342, 0.00005);
near('K6', '最低', Math.min(...TB80), 7.07, 1e-9);
is('K6', '最低出现在 6 月', TB80.indexOf(Math.min(...TB80)) === 5);
near('K6', '最高', Math.max(...TB80), 15.49, 1e-9);
is('K6', '最高出现在 12 月', TB80.indexOf(Math.max(...TB80)) === 11);
is('K6', '每个月都高于 5.25%', TB80.every(x => x > 5.25));
is('K6', '中美取消存款利率上限相隔约三十年（1986 → 2015）', 2015 - 1986 === 29);
// 第七节：今天（官方公布值 3.7%）
near('N2', '0.39% 对 3.7%：近似（课文「约 −3.3」）', approx(0.39, 3.7), -3.31, P);
near('N2', '0.39% 对 3.7%：精确（课文「约 −3.2%」）', exact(0.39, 3.7), -3.19, P);
is('N2', '用 3.7377 或 3.7，精确值四舍五入都是 −3.2', Math.round(exact(0.39, pi26) * 10) / 10 === -3.2 && Math.round(exact(0.39, 3.7) * 10) / 10 === -3.2);
is('N2', '定期存款 1.81% 低于 3.7%', 1.81 < 3.7);
near('N2', '现金：名义 0 对 3.7%（课文「约 −3.6%」）', exact(0, 3.7), -3.57, P);

console.log(out.join('\n'));
