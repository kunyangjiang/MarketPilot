// 读取《S06-01 课文 v1 候选.md》与《S06-01 图与交互方案 v1 候选.md》。
// 教学模型的数字：先独立重算，再断言课文（及图方案）里确实以该写法出现。
// 文献与官方数据的数字：重算其中的差值、比值，并断言原值出现；原值出处见核验记录。
// 不依赖网络与临时目录。
'use strict';
const fs = require('fs');
const path = require('path');

const LESSON = fs.readFileSync(path.join(__dirname, 'S06-01 课文 v1 候选.md'), 'utf8').replace(/\r/g, '');
const FIG = fs.readFileSync(path.join(__dirname, 'S06-01 图与交互方案 v1 候选.md'), 'utf8').replace(/\r/g, '');

let pass = 0, fail = 0;
function ok(id, cond, msg) { if (cond) pass++; else { fail++; console.log('失败 ' + id + '：' + (msg || '')); } }
const near = (a, b, tol) => Math.abs(a - b) < (tol || 1e-9);
function num(id, got, want, dp, text, fig) {
  const r = Number(got.toFixed(dp));
  ok(id + ' 重算', near(r, want), `重算 ${got} → ${r}，应为 ${want}`);
  if (text) ok(id + ' 课文出现', LESSON.includes(text), `课文里没有「${text}」`);
  if (fig) ok(id + ' 图方案出现', FIG.includes(fig === true ? text : fig), `图方案里没有「${fig === true ? text : fig}」`);
}
const inL = (id, s) => ok(id + ' 课文出现', LESSON.includes(s), `课文里没有「${s}」`);
const inF = (id, s) => ok(id + ' 图方案出现', FIG.includes(s), `图方案里没有「${s}」`);

// ---------- A 组：图 1，财政部收益率（官方数据，S0601-R07） ----------
const T = { // [前一交易日, 当日]
  bill3m_jan: [5.87, 5.69], bill3m_mar: [4.53, 4.49],
  y10_jan: [4.92, 5.14], y10_mar: [4.82, 4.78],
};
num('A1 1月3日 3个月期变化', T.bill3m_jan[1] - T.bill3m_jan[0], -0.18, 2, '5.87% → 5.69%，下降 0.18 个百分点', true);
num('A2 3月20日 3个月期变化', T.bill3m_mar[1] - T.bill3m_mar[0], -0.04, 2, '4.53% → 4.49%，下降 0.04 个百分点', true);
num('A3 1月3日 10年期变化', T.y10_jan[1] - T.y10_jan[0], 0.22, 2, '4.92% → 5.14%，上升 0.22 个百分点', true);
num('A4 3月20日 10年期变化', T.y10_mar[1] - T.y10_mar[0], -0.04, 2, '4.82% → 4.78%，下降 0.04 个百分点', true);
inL('A5 正文 0.18', '它下降了 0.18 个百分点');
inL('A6 正文 0.04', '只下降了 0.04 个百分点');
inL('A7 正文 10年期 0.22', '10 年期收益率却上升了 0.22 个百分点');
ok('A8 「好几倍」成立', 0.18 / 0.04 >= 4, '0.18 ÷ 0.04 = ' + (0.18 / 0.04));
inL('A9 好几倍', '差了好几倍');
// FOMC 决定（S0601-R05、R06）
inL('A10 1月目标 6%', '下调 0.5 个百分点，到 6%');
inL('A11 3月目标 5%', '下调 0.5 个百分点，到 5%');
inL('A12 1月31日 5.5%', '1 月 31 日的例会又降了 0.5 个百分点，到 5.5%');
num('A13 三次合计', (6.5 - 0.5) - 0.5 - 0.5, 5.0, 2, '再把目标下调 0.5 个百分点，到 5%'); // 6.5% → 6% → 5.5% → 5%（R05、R11、R06）
// 股市一日回报（S0403-R04 第 8 页，论文统计量）
inL('A14 1月3日 +5.3%', '当天涨了 5.3%'); inF('A14 图方案', '上涨 5.3%');
inL('A15 3月20日 跌 2% 多', '指数当天跌了 2% 多'); inF('A15 图方案', '下跌 2% 多');
inL('A16 未请求 0.75', '没有降 0.75 个百分点');

// ---------- B 组：三家公司的意外（教学假设） ----------
const eps0 = 5.00, eps1 = 6.00;
num('B1 增长 20%', eps1 / eps0 - 1, 0.20, 4, '都比去年多赚 20%');
const expv = { 甲: 6.25, 乙: 6.00, 丙: 5.50 };
num('B2 甲意外', eps1 - expv.甲, -0.25, 2, '−$0.25');
num('B3 丙意外', eps1 - expv.丙, 0.50, 2, '+$0.50');
num('B4 甲比例', (eps1 - expv.甲) / expv.甲 * 100, -4.0, 1, '| −4.0% |');
num('B5 丙比例', (eps1 - expv.丙) / expv.丙 * 100, 9.1, 1, '约 +9.1% |');
inL('B6 正文 甲跌 4%', '公司甲的股价大约跌 4%');
inL('B7 正文 丙涨 9.1%', '公司丙大约涨 9.1%');
inL('B8 要点', '意外分别是 −4.0%、0、约 +9.1%');
inL('B9 要点预期', '预期为 $6.25、$6.00、$5.50 时');

// ---------- C 组：异常回报（正文例与小题 2，教学假设） ----------
const rel = 1.2;
num('C1 正文例 正常回报', rel * 1, 1.2, 2, '它的正常回报就是 1.2%');
num('C2 正文例 异常回报', 4 - rel * 1, 2.8, 2, '异常回报就是 4% − 1.2% = 2.8%');
num('C3 小题2 正常回报', rel * -2, -2.4, 2, '1.2 × (−2%) = −2.4%', true);
num('C4 小题2 异常回报', -3 - rel * -2, -0.6, 2, '−3% − (−2.4%) = −0.6%', true);
inL('C5 小题2 选项C', 'C. −0.6%');

// ---------- D 组：鲍尔与布朗（1968）报告的数（S0601-R01） ----------
num('D1 好消息组累计', (1.071 - 1) * 100, 7.1, 1, '累计多涨了约 7.1%');
num('D2 坏消息组累计', (0.907 - 1) * 100, -9.3, 1, '累计少涨了约 9.3%');
inF('D3 图方案 1.071', '约 1.071'); inF('D4 图方案 0.907', '约 0.907');
inL('D5 图2 说明 1.071', '好消息组约 1.071'); inL('D6 图2 说明 0.907', '坏消息组约 0.907');
inL('D7 85%–90%', '85% 到 90%');
inL('D8 261 家', '261 家'); inL('D9 年份', '1957 到 1965 这九个会计年度');
ok('D10 1957–1965 是九年', 1965 - 1957 + 1 === 9);
inL('D11 数据年份', '1946 到 1966 年');
inF('D12 图方案 +7.1%', '约 +7.1%'); inF('D13 图方案 −9.3%', '约 −9.3%');

// ---------- E 组：教学模型（增长永续，S04-05 框架） ----------
const price = (E1, b, roi, r) => (E1 * (1 - b)) / (r - b * roi);
// 独立核对：逐年现金流折现（截断 4000 年），不用封闭公式
function pvSim(E1, b, roi, r, N = 4000) {
  const g = b * roi; let pv = 0, f = E1 * (1 - b);
  for (let t = 1; t <= N; t++) { pv += f / Math.pow(1 + r, t); f *= 1 + g; }
  return pv;
}
const base = { E1: 6.00, b: 0.5, roi: 0.14, r: 0.10 };
num('E1 起点增长率', base.b * base.roi * 100, 7, 4, '增长率是 50% × 14% = 7%');
num('E2 起点自由现金流', base.E1 * (1 - base.b), 3.00, 2, '即 $3.00');
const P0 = price(base.E1, base.b, base.roi, base.r);
num('E3 起点股价', P0, 100, 6, '$3.00 ÷（10% − 7%）= **$100**', '股价 $100');
ok('E3b 逐年模拟', near(pvSim(base.E1, base.b, base.roi, base.r), P0, 1e-6), 'pvSim=' + pvSim(base.E1, base.b, base.roi, base.r));
// 第一步：E1 → 6.30
num('E4 每股收益 +5%', (6.30 / 6.00 - 1) * 100, 5, 6, '从 $6.00 上调到 $6.30，多了 5%');
const P1 = price(6.30, base.b, base.roi, base.r);
num('E5 第一步股价', P1, 105, 6, '$3.15 ÷ 3% = **$105**', '股价 $105（+5%）');
num('E5b 自由现金流 3.15', 6.30 * 0.5, 3.15, 4, '明年的自由现金流变成 $3.15');
ok('E5c 逐年模拟', near(pvSim(6.30, base.b, base.roi, base.r), P1, 1e-6));
// 第二步：roi → 13%
num('E6 第二步增长率', 0.5 * 0.13 * 100, 6.5, 4, '增长率变成 50% × 13% = 6.5%');
const P2 = price(6.30, base.b, 0.13, base.r);
num('E7 第二步股价', P2, 90, 6, '$3.15 ÷（10% − 6.5%）= **$90**', '股价 $90（相对起点 −10%）');
ok('E7b 逐年模拟', near(pvSim(6.30, base.b, 0.13, base.r), P2, 1e-6));
num('E8 第二步相对起点', (P2 / P0 - 1) * 100, -10, 6, '股价却跌了 10%');
// 盈亏平衡：3.15 / (0.10 − g*) = 100
const gStar = base.r - 3.15 / 100, roiStar = gStar / base.b;
num('E9 盈亏平衡增长率', gStar * 100, 6.85, 4, '增长率从 7% 降到 6.85%', '增长率 6.85%');
num('E10 盈亏平衡回报率', roiStar * 100, 13.7, 4, '只需要从 14% 降到 13.7%', '回报率降到 13.7% 时回到 $100');
num('E11 增长率少 0.15 个百分点', (0.07 - gStar) * 100, 0.15, 4, '只少 0.15 个百分点');
num('E12 敏感度 1÷3%', 1 / 0.03, 33.3, 1, '1 ÷ 3% ≈ 33');
num('E13 0.15 × 33 ≈ 5%', 0.15 * (1 / 0.03), 5.0, 1, '正好约是 5%');
// 用数值导数核对「对 g 的敏感度与对 r 的敏感度大小相同」
const h = 1e-6;
const dlnP_dg = (Math.log(price(6.30, 0.5, (0.07 + h) / 0.5, 0.10)) - Math.log(price(6.30, 0.5, 0.07 / 0.5, 0.10))) / h;
const dlnP_dr = (Math.log(price(6.30, 0.5, 0.14, 0.10 + h)) - Math.log(price(6.30, 0.5, 0.14, 0.10))) / h;
ok('E14 对 g 与对 r 的敏感度大小相同、方向相反', near(dlnP_dg, -dlnP_dr, 1e-2) && near(dlnP_dg, 1 / 0.03, 1e-2), `${dlnP_dg} vs ${dlnP_dr}`);
inL('E15 方向相反', '对增长率的敏感度也是这么大，方向相反');
// 第三步：r → 10.5%
const P3 = price(base.E1, base.b, base.roi, 0.105);
num('E16 第三步股价', P3, 85.71, 2, '≈ **$85.71**', '约 $85.71');
ok('E16b 逐年模拟', near(pvSim(base.E1, base.b, base.roi, 0.105), P3, 1e-6));
num('E17 第三步跌幅', (P3 / P0 - 1) * 100, -14.3, 1, '跌约 14.3%', '约 −14.3%');
// 按新价格买入并持有的预期回报 = F/P + g
num('E18 持有回报 10.5%', (3.00 / P3 + 0.07) * 100, 10.5, 6, '以后每年的预期回报是 10.5%');
// 要点
inL('E19 要点', '股价 $100；利润超出预期 5% → $105；同时新投资回报率从 14% 下调到 13% → $90；回报率只需降到 13.7% 就抵掉 5% 的利润惊喜；折现率升到 10.5%、现金不变 → 约 $85.71');
inF('E20 图方案 起点输入', '明年每股收益 $6.00，再投资率 50%，新投资回报率 14%，增长率 7%，折现率 10%，自由现金流 $3.00');
inF('E21 图方案 6.30', '每股收益预期升到 $6.30');

// ---------- F 组：坎贝尔（S0601-R02）、武尔泰纳霍（S0601-R04）、伯南克与库特纳（S0403-R04） ----------
inL('F1 坎贝尔三分之一到一半', '三分之一到一半');
inL('F2 坎贝尔 4% 到 5%', '伴随的是 4% 到 5% 的资本损失');
inL('F3 坎贝尔样本', '1927 到 1988 年的月度数据');
inL('F4 坎贝尔 1952', '1952 年以后才很强');
const V = { ex: [0.1002, 0.0645], adj: [0.0801, 0.0161] };
num('F5 超额回报口径倍数', V.ex[0] / V.ex[1], 1.6, 1, '| 0.1002 | 0.0645 | 1.6 倍 |');
num('F6 扣市场平均口径倍数', V.adj[0] / V.adj[1], 5, 0, '| 0.0801 | 0.0161 | 5 倍 |');
inL('F7 等权组合', '约四分之三');
inL('F8 样本', '1954 到 1996 年');
