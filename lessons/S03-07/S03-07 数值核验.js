// S03-07 数值核验：node "lessons/S03-07/S03-07 数值核验.js"
// 读取《S03-07 课文 v1 候选.md》与《S03-07 图与交互方案 v1 候选.md》，对每个关键数字既重算、又断言它出现在文件里。
// 不依赖网络或临时目录。所有价格都是课文写明的假设数；规则数字（FINRA 4210 的 100% / 20% / 10%）按核验记录中的来源抄录于此。
'use strict';
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const lesson = fs.readFileSync(path.join(dir, 'S03-07 课文 v1 候选.md'), 'utf8').replace(/\r/g, '');
const figs = fs.readFileSync(path.join(dir, 'S03-07 图与交互方案 v1 候选.md'), 'utf8').replace(/\r/g, '');

let pass = 0, fail = 0;
function ok(id, desc, cond) { if (cond) pass++; else { fail++; console.log('失败 ' + id + '：' + desc); } }
const near = (a, b, tol) => Math.abs(a - b) <= (tol === undefined ? 1e-9 : tol);
const inL = s => lesson.includes(s);
const inF = s => figs.includes(s);
function num(id, desc, value, expected, strs, where) {
  ok(id, desc + ' 重算 ' + value + ' ≈ ' + expected, near(value, expected));
  for (const s of strs || []) ok(id, desc + ' 出现「' + s + '」于' + (where === 'F' ? '图方案' : where === 'LF' ? '课文与图方案' : '课文'),
    where === 'F' ? inF(s) : where === 'LF' ? (inL(s) && inF(s)) : inL(s));
}
const money = x => (x < 0 ? '−' : '') + '$' + Math.abs(x).toLocaleString('en-US', { minimumFractionDigits: Number.isInteger(x) ? 0 : 2 });
const signed = (x, dp) => (x > 0 ? '+' : x < 0 ? '−' : '') + '$' + Math.abs(x).toLocaleString('en-US', { minimumFractionDigits: dp, maximumFractionDigits: dp });

// 假设（课文第 1、3 节）
const S0 = 50, K = 50, C = 3.00, P = 2.75, N = 100;
const callPay = s => Math.max(s - K, 0), putPay = s => Math.max(K - s, 0);
const lc = s => callPay(s) - C, sc = s => -lc(s), lp = s => putPay(s) - P, sp = s => -lp(s);
ok('A0', '假设数出现于课文与图方案', inL('$50') && inL('$3.00') && inL('$2.75') && inF('3.00') && inF('2.75'));

// A 开场（第 1 节）：看跌买方最多亏 2.75；卖方在 $30 时每股亏 20、净亏 17.25
num('A1', '开场卖方每股亏', K - 30, 20, ['每股亏 $20']);
num('A2', '开场卖方净亏', -sp(30) * 1, 17.25, ['$17.25']);

// B 买入看涨（第 3 节表；图 1）
const t3 = [[40, 0, -3], [50, 0, -3], [53, 3, 0], [60, 10, 7], [70, 20, 17]];
for (const [s, pay, pl] of t3) {
  num('B-' + s, '买看涨 到期收益 @' + s, callPay(s), pay);
  num('B-' + s, '买看涨 盈亏 @' + s, lc(s), pl);
}
ok('B1', '第 3 节表格行出现于课文', inL('| 到期收益 | $0 | $0 | $3 | $10 | $20 |') && inL('| 减去权利金后的盈亏 | −$3 | −$3 | $0 | +$7 | +$17 |'));
num('B2', '看涨盈亏平衡点', K + C, 53, ['$50 + $3 = $53'], 'L');
ok('B3', '图 1 数字出现于课文与图方案', inL('$60 → $10') && inL('$70 → $20') && inF('$60 → 到期收益 $10') && inF('盈亏平衡点 $53') && inF('−$3'));
// 小题 1：股价 52，1 张
num('B4', '小题 1：1 张盈亏', lc(52) * N, -100, ['亏 $100', '收回 $2', '挽回 $200']);

// C 卖出看涨（第 4 节）
num('C1', '卖看涨 @60 每股', sc(60), -7, ['净亏 $7']);
num('C2', '卖看涨 @70 每股', sc(70), -17, ['净亏 $17']);
num('C3', '卖看涨 @100 每张', sc(100) * N, -4700, ['$4,700'], 'LF');
num('C4', '卖看涨 @150 每张', sc(150) * N, -9700, ['$9,700'], 'LF');
// 备兑看涨：100 股（今天 $5,000）+ 卖 1 张 @3
const cov = s => (Math.min(s, K) - S0 + C) * N;
num('C5', '备兑 @60', cov(60), 300, ['收下 $300', '多了 $300']);
num('C6', '不卖期权 @60', (60 - S0) * N, 1000, ['多 $1,000']);
num('C7', '备兑 @40', cov(40), -700, ['净少 $700']);
num('C8', '100 股今天市值', S0 * N, 5000, ['今天市值 $5,000']);

// D 看跌（第 5 节）
num('D1', '看跌盈亏平衡', K - P, 47.25, ['$47.25']);
num('D2', '买看跌 @40', lp(40), 7.25, ['净赚 $7.25']);
num('D3', '买看跌 @30', lp(30), 17.25, ['净赚 $17.25']);
num('D4', '买看跌最大盈利', lp(0), 47.25, ['$50 − $2.75 = $47.25']);
num('D5', '卖看跌 @40', sp(40), -7.25, ['每股净亏 $7.25']);
num('D6', '卖看跌最坏每张', sp(0) * N, -4725, ['$4,725'], 'LF');
num('D7', '现金担保 1 张', K * N, 5000, ['1 张就是 $5,000']);
ok('D8', '卖看跌最坏是权利金的十几倍', 47.25 / 2.75 > 10 && 47.25 / 2.75 < 20 && inL('十几倍'));
// 四头寸总表
ok('D9', '总表四行', inL('| 买入看涨 | 没有上限 | $3（权利金） | $53 | 股价高于 $53 |') &&
  inL('| 卖出看涨（手里没有股票） | $3（权利金） | 没有上限 | $53 | 股价低于 $53 |') &&
  inL('| 买入看跌 | $47.25（股价跌到 0） | $2.75（权利金） | $47.25 | 股价低于 $47.25 |') &&
  inL('| 卖出看跌 | $2.75（权利金） | $47.25（股价跌到 0） | $47.25 | 股价高于 $47.25 |'));
// 小题 2：卖 1 张看跌，股价 40
num('D10', '小题 2', sp(40) * N, -725, ['亏 $725', '每股亏 $10']);

// E 图 2：九个预设价位（图方案表）与零和、上下限
const pre = [0, 30, 40, 47.25, 50, 53, 60, 70, 100];
for (const s of pre) {
  const row = '| $' + s + ' | ' + [lc(s), sc(s), lp(s), sp(s)].map(x => signed(x, 2)).join(' | ') + ' |';
  ok('E-' + s, '图 2 预设价位行 ' + row, inF(row));
}
ok('E1', '课文图 2 说明的读数整句', inL('股价 $60：买入看涨 +$7.00，卖出看涨 −$7.00，买入看跌 −$2.75，卖出看跌 +$2.75'));
let zs = true, cap = true;
for (let s = 0; s <= 100; s += 0.25) {
  zs = zs && near(lc(s) + sc(s), 0) && near(lp(s) + sp(s), 0);
  cap = cap && lc(s) >= -C - 1e-9 && sc(s) <= C + 1e-9 && lp(s) >= -P - 1e-9 && sp(s) <= P + 1e-9 && lp(s) <= K - P + 1e-9 && sp(s) >= -(K - P) - 1e-9;
}
ok('E2', '滑块全程（每 $0.25）零和', zs);
ok('E3', '滑块全程：买方亏损以权利金为限，卖方收益以权利金为限，看跌两边以 47.25 为界', cap);
ok('E4', '滑块范围出现于两份文件', inL('$0 到 $100，步长 $0.25') && inF('$0–$100，步长 $0.25'));

// F 保证金（第 6 节；FINRA 4210(f)(2)(E)(i)：100% 期权市价 + 20% 标的市值，减价外，下限 期权市价 + 10%）
const base = C * N + 0.20 * S0 * N - 0, floor = C * N + 0.10 * S0 * N;
num('F1', '期权市价 100%', C * N, 300, ['| 期权市价的 100%：$3 × 100 | $300 |']);
num('F2', '标的市值 20%', 0.20 * S0 * N, 1000, ['| 加上股票市值的 20%：$50 × 100 × 20% | $1,000 |']);
num('F3', '合计', base, 1300, ['| 合计 | $1,300 |', '最低要求是 $1,300']);
num('F4', '下限', floor, 800, ['| 对照下限：$300 + $50 × 100 × 10% | $800 |']);
ok('F5', '取较高者', Math.max(base, floor) === 1300 && inL('$1,300 高于下限'));

// G 保险（第 7 节；图 3）：600 股，6 张
const sh = 600, n = sh / N, mv = S0 * sh;
const only = s => (s - S0) * sh, k50 = s => (Math.max(s, 50) - S0 - 2.75) * sh, k45 = s => (Math.max(s, 45) - S0 - 0.90) * sh;
num('G1', '6 张', n, 6, ['6 张']);
num('G2', 'K50 权利金合计', n * N * 2.75, 1650, ['$1,650'], 'LF');
num('G3', 'K45 权利金合计', n * N * 0.90, 540, ['$540', '$0.90'], 'LF');
num('G4', '今天市值', mv, 30000, ['$30,000'], 'LF');
num('G5', '免赔额 600 股', 5 * sh, 3000, ['$3,000'], 'LF');
const cols = [30, 40, 45, 50, 60, 70];
const rowStr = (label, f) => '| ' + label + ' | ' + cols.map(s => { const v = f(s); return v === 0 ? '$0' : signed(v, 0); }).join(' | ') + ' |';
const r1 = rowStr('只持有股票', only), r2L = rowStr('加买行权价 $50 的看跌（$1,650）', k50), r3L = rowStr('加买行权价 $45 的看跌（$540）', k45);
ok('G6', '第 7 节表：只持股 ' + r1, inL(r1) && inF(r1));
ok('G7', '第 7 节表：K50 ' + r2L, inL(r2L));
ok('G8', '第 7 节表：K45 ' + r3L, inL(r3L));
ok('G9', '图 3 表：K50 / K45', inF(rowStr('加买 K50（$1,650）', k50)) && inF(rowStr('加买 K45（$540）', k45)));
num('G10', '股价 70 时保险少赚', only(70) - k50(70), 1650, ['少赚 $1,650']);
num('G11', '小题 4：K45、股价 38', k45(38), -3540, ['少 $3,540', '每股少 $5.90', '每股比今天少 $5']);
num('G12', '小题 4 选项 B（没买保险）', only(38), -7200, ['少 $7,200']);
num('G13', '前 $5 下跌', 50 - 45, 5, ['每股前 $5 的下跌']);
num('G14', '比方第二处：$60 → $50', 60 - 50, 10, ['那 $10']);

// H 合约规格与史实数字
ok('H1', '1 张 = 100 股；看跌 1 张 $275', near(P * N, 275) && inL('1 张合约对应 100 股') && inL('买 1 张要付 $275'));
ok('H2', '600 股要 6 张', sh / N === 6 && inL('就得买 6 张'));
ok('H3', 'Cboe 开始交易日期', inL('1973 年 4 月 26 日'));
ok('H4', '50ETF 期权日期与规格', inL('2015 年 2 月 3 日') && inL('2015 年 2 月 9 日') && inL('10,000 份'));
ok('H5', '适当性门槛与三级', inL('50 万元') && inL('一级') && inL('二级') && inL('三级'));

console.log('通过 ' + pass + '，失败 ' + fail);
if (fail) process.exit(1);
