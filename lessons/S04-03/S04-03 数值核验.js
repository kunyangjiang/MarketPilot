// ---------- 方法一：逐笔折现（循环） ----------
function bondLoop(c, y, n, f) {
  f = f || 1; let P = 0, T = 0;
  for (let k = 1; k <= n * f; k++) {
    const cf = 100 * c / f + (k === n * f ? 100 : 0);
    const pv = cf / Math.pow(1 + y / f, k);
    P += pv; T += pv * k / f;
  }
  return { P, D: T / P, MD: (T / P) / (1 + y / f) };
}
// ---------- 方法二：闭式（年金 + 本金；久期用闭式公式） ----------
function bondClosed(c, y, n, f) {
  f = f || 1; const i = y / f, N = n * f, C = 100 * c / f;
  const v = Math.pow(1 + i, -N);
  const P = C * (1 - v) / i + 100 * v;
  // 麦考利久期闭式（以期数计，再除以 f）：D = (1+i)/i − (1+i+N(C/100 − i)) / ((C/100)((1+i)^N − 1) + i)
  const cc = C / 100;
  const Dp = (1 + i) / i - (1 + i + N * (cc - i)) / (cc * (Math.pow(1 + i, N) - 1) + i);
  return { P, D: Dp / f, MD: Dp / f / (1 + i) };
}
