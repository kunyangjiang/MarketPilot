function near(a, b, tol) { return Math.abs(a - b) < (tol || 1e-9); }
// 重算值四舍五入到 dp 位应等于 want；text 必须出现在课文（可选：也出现在图方案）
function num(id, got, want, dp, text, opts = {}) {
  const r = Number(got.toFixed(dp));
  ok(id + ' 重算', near(r, want), `重算 ${got} → ${r}，应为 ${want}`);
  if (text && opts.lesson !== false) ok(id + ' 课文出现', LESSON.includes(text), `课文里没有「${text}」`);
  if (opts.fig) ok(id + ' 图方案出现', FIG.includes(opts.fig === true ? text : opts.fig), `图方案里没有「${opts.fig === true ? text : opts.fig}」`);
}
const inL = (id, s) => ok(id + ' 课文出现', LESSON.includes(s), `课文里没有「${s}」`);
const inF = (id, s) => ok(id + ' 图方案出现', FIG.includes(s), `图方案里没有「${s}」`);

// 模型：单位亿美元。E1 = 明年利润；b = 再投资率；roi = 新投资回报率；r = 折现率
const R = 0.10, E1 = 1;
const g = (b, roi) => b * roi;
const fcf = (b, roi, t) => (1 - b) * E1 * Math.pow(1 + g(b, roi), t - 1);
const value = (b, roi, r = R) => (1 - b) * E1 / (r - g(b, roi));
// 独立核对：逐年模拟资本与利润，截断 3000 年求现值（不用封闭公式）
function simulate(b, roi, r = R, T = 3000) {
  let profit = E1, pvSum = 0;
  for (let t = 1; t <= T; t++) {
    const invest = b * profit;
    pvSum += (profit - invest) / Math.pow(1 + r, t);
    profit += invest * roi;              // 下一年起每年多赚 invest × roi
  }
  return pvSum;
}
function crossYear(b, roi) { for (let t = 1; t < 1000; t++) if (fcf(b, roi, t) >= E1 - 1e-12) return t; return null; }

