// 回报率公式与增长永续互逆：按 P 买入、持有 1000 年的内部收益率
function irr(F, P, gg) { let lo = gg + 1e-9, hi = 1; for (let k = 0; k < 200; k++) { const m = (lo + hi) / 2; let pv = 0; for (let t = 1; t <= 4000; t++) pv += F * Math.pow(1 + gg, t - 1) / Math.pow(1 + m, t); if (pv > P) lo = m; else hi = m; } return (lo + hi) / 2; }
ok('E7 内部收益率独立核对（B 按 25 亿）', near(irr(0.5, 25, 0.075), 0.095, 1e-5), 'irr ' + irr(0.5, 25, 0.075));
