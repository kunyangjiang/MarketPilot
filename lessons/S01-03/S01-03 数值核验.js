// 投资利率：31 CFR 356 附录 B 第 VI 节 D.2（期限超过半年）
//   P[1 + (r − y/2)(i/y)](1 + i/2) = 100；a = r/(2y) − .25，b = r/y，c = (P − 100)/P，i = (−b + √(b² − 4ac)) / 2a
const yDays = (Date.UTC(2027, 9, 29) - Date.UTC(2026, 9, 29)) / 86400000; // 发行日到一年后同日，不含 2 月 29 日
near('H3', 'y（发行日后一年的天数）', yDays, 365, 0);
function investRate(P, r, y) {
  const a = r / (2 * y) - 0.25, b = r / y, c = (P - 100) / P;
  return (-b + Math.sqrt(b * b - 4 * a * c)) / (2 * a);
}
