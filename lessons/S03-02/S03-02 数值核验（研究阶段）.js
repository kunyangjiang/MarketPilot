let pass = 0, fail = 0;
function near(id, label, got, want, tol = 0.005) {
  const ok = Math.abs(got - want) <= tol;
  ok ? pass++ : fail++;
  console.log(`${ok ? 'OK ' : 'FAIL'} ${id} ${label}: ${got.toFixed(6)} (期望 ${want})`);
}
// 一般定价：cfs = [[t(期数), 金额], ...]，per = 每期折现率
const pv = (cfs, per) => cfs.reduce((s, [t, c]) => s + c / Math.pow(1 + per, t), 0);
// 由价格反解每期收益率（二分法）
function solve(cfs, price) {
  let lo = -0.5, hi = 1;
  for (let k = 0; k < 200; k++) { const m = (lo + hi) / 2; pv(cfs, m) > price ? (lo = m) : (hi = m); }
  return (lo + hi) / 2;
}

