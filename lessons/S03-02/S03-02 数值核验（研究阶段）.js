// ---------- G. 真实国债：2 年期 91282CDR9 ----------
// 拍卖价复算：31 CFR 356 附录 B II.A：P[1 + (r/s)(i/2)] = (C/2)(r/s) + (C/2)a_n + 100 v^n；发行日即付息基准日，r = s，n = 3
{
  const i = 0.00769, C = 0.75, n = 3, h = i / 2;
  const v = 1 / (1 + h), vn = v ** n, an = (1 - vn) / h;
  const P = ((C / 2) * 1 + (C / 2) * an + 100 * vn) / (1 + h);
  near('G1', '拍卖价复算（附录 B 公式）', P, 99.962362, 5e-7);
  near('G1b', '等价写法：4 个半年现金流按 0.3845% 折现', pv([[1, .375], [2, .375], [3, .375], [4, 100.375]], h), 99.962362, 5e-7);
}
