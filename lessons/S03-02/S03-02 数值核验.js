let pass = 0, fail = 0;
function ok(id, cond, msg) {
  if (cond) pass++; else { fail++; console.log('失败 ' + id + '：' + msg); }
}
// 重算值四舍五入到 dp 位后应等于 want；want 的写法必须出现在课文（以及可选的图方案）里
function num(id, got, want, dp, opts = {}) {
  const r = Number(got.toFixed(dp));
  ok(id + ' 重算', Math.abs(r - Number(want)) < 1e-9, `重算 ${got} → ${r}，课文写 ${want}`);
  const s = opts.text || String(want);
  if (opts.lesson !== false) ok(id + ' 课文出现', LESSON.includes(s), `课文里没有「${s}」`);
  if (opts.fig) ok(id + ' 图方案出现', FIG.includes(opts.figText || s), `图方案里没有「${opts.figText || s}」`);
}
function inL(id, s) { ok(id + ' 课文出现', LESSON.includes(s), `课文里没有「${s}」`); }
function inF(id, s) { ok(id + ' 图方案出现', FIG.includes(s), `图方案里没有「${s}」`); }

const pv = (cfs, r) => cfs.reduce((s, c, k) => s + c / Math.pow(1 + r, k + 1), 0);
function solve(cfs, price) { // 二分法求每期收益率
  let lo = -0.5, hi = 1;
  for (let i = 0; i < 200; i++) { const m = (lo + hi) / 2; if (pv(cfs, m) > price) lo = m; else hi = m; }
  return (lo + hi) / 2;
}

