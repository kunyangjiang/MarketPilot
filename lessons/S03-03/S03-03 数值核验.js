// 读取《S03-03 课文 v1 候选.md》和《S03-03 图与交互方案 v1 候选.md》，对每个关键数字：先重算，再断言它确实出现在文件里。
// 不依赖网络或临时目录。
// 本课独立假设（设定表第二节）：一年期国债 4.00%；一年期零息债券到期付 $100；违约损失率 60%；
//   东川电力（虚构）违约概率 0.1%、市场利差 0.90 个百分点；北岭电池违约概率 4%、市场利差 4.00 个百分点。
// 研究数字：Elton 等工作论文（1999）表 I、VI、VII；旧金山联储 Economic Letter 2010-06；Longstaff 等 NBER WP 10418（2004）；
//   Feldhütter & Schaefer（RFS 2018）；Huang, Nozawa & Shi（JF 2025）；S01-05 的 HQM 与 GS10（2026 年 10 月）。
'use strict';
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const lesson = fs.readFileSync(path.join(dir, 'S03-03 课文 v1 候选.md'), 'utf8');
const figs = fs.readFileSync(path.join(dir, 'S03-03 图与交互方案 v1 候选.md'), 'utf8');

let pass = 0, fail = 0;
function ok(cond, msg) { if (cond) pass++; else { fail++; console.log('失败：' + msg); } }
const close = (a, b, tol = 1e-9) => Math.abs(a - b) <= tol;
const r2 = x => Math.round(x * 100) / 100;
const inL = (s, msg) => ok(lesson.includes(s), '课文缺「' + s + '」' + (msg ? '（' + msg + '）' : ''));
const inF = (s, msg) => ok(figs.includes(s), '图方案缺「' + s + '」' + (msg ? '（' + msg + '）' : ''));
const inBoth = (s, msg) => { inL(s, msg); inF(s, msg); };

// ---------- 模型 ----------
const r = 0.04, LGD = 0.6;
function bond(p, s) {
  const EL = p * LGD;
  const avg = 100 * (1 - EL);
  const fair = avg / (1 + r);
  const fairY = 100 / fair - 1;
  const fairS = fairY - r;
  const mkt = 100 / (1 + r + s);
  const q = (1 - mkt * (1 + r) / 100) / LGD;
  return { EL, avg, fair, fairY, fairS, mkt, gap: s - fairS, q, mult: q / p, share: EL / s };
}
const D = bond(0.001, 0.009), N = bond(0.04, 0.04);

// 第 1 节：开场表
ok(r2(D.mkt) === 95.33 && r2(N.mkt) === 92.59, '市场价 $95.33 / $92.59');
inL('| 每张债券今天的价格 | $95.33 | $92.59 |');
inL('| 到期收益率 | 4.90% | 8.00% |');
inL('| 比一年期国债高出 | 0.90 个百分点 | 4.00 个百分点 |');
ok(close(r + 0.009, 0.049) && close(r + 0.04, 0.08), '总收益率 4.90% / 8.00%');
ok((0.04 / 0.009).toFixed(1) === '4.4', '利差之比约 4.4 倍'); inL('约 4.4 倍');
ok((0.08 / 0.049).toFixed(1) === '1.6', '总利率之比约 1.6 倍'); inL('1.6 倍左右');
inL('一年期国债的收益率假设是 4.00%');

// 第 2 节：平均拿回、精算价、利差
ok(close(D.EL, 0.0006) && close(N.EL, 0.024), '预期违约损失 0.06% / 2.40%');
inL('$100 × (1 − 0.1% × 60%) = $100 × (1 − 0.06%) = $99.94');
inL('$100 × (1 − 4% × 60%) = $100 × (1 − 2.40%) = $97.60');
ok(close(D.avg, 99.94) && close(N.avg, 97.6), '平均拿回 $99.94 / $97.60');
ok(r2(D.fair) === 96.10 && r2(N.fair) === 93.85, '精算价 $96.10 / $93.85');
inL('$99.94 ÷ 1.04 ≈ $96.10'); inL('$97.60 ÷ 1.04 ≈ $93.85');
ok((D.fairY * 100).toFixed(2) === '4.06' && (N.fairY * 100).toFixed(2) === '6.56', '精算收益率 4.06% / 6.56%');
inL('约 4.06%'); inL('约 6.56%');
ok((D.fairS * 100).toFixed(2) === '0.06' && (N.fairS * 100).toFixed(2) === '2.56', '只补偿平均损失时的利差 0.06 / 2.56');
inL('比国债高约 0.06 个百分点'); inL('比国债高约 2.56 个百分点');
inL('北岭电池按近似算是 2.40，精确算是 2.56');
// 精确式与近似：s = (1+r)/(1-EL) - 1 - r
ok(close(N.fairS, (1 + r) / (1 - N.EL) - 1 - r, 1e-12), '精确式一致');
ok(N.fairS > N.EL && D.fairS > D.EL, '精确值大于近似值（损失按面值、收益率按更低的价格）');

// 图 1
ok((D.gap * 100).toFixed(2) === '0.84' && (N.gap * 100).toFixed(2) === '1.44', '差额 0.84 / 1.44');
inL("东川电力是 0.06 与 0.90"); inF("东川电力：0.06 与 0.90"); inL('北岭电池是 2.56 与 4.00');
inL('东川电力 0.84，北岭电池 1.44');
ok(Math.round(D.share * 100) === 7 && Math.round(N.share * 100) === 60, '近似占比 约 7% / 约 60%');
inBoth('东川电力约 7%，北岭电池约 60%');
ok(Math.round(N.fairS / 0.04 * 100) === 64, '精确占比 约 64%'); inL('按精确值 2.56 算约占 64%');
inL('其余 0.84 个百分点');
inF('| 预期违约损失 | 0.06% | 2.40% |'); inF('| 平均拿回 | $99.94 | $97.60 |'); inF('| 精算价 | $96.10 | $93.85 |');
inF('| 精算收益率 | 4.06% | 6.56% |'); inF('| 只补偿平均损失时的利差 | 0.06 | 2.56 |'); inF('| 市场利差 | 0.90 | 4.00 |');
inF('| 市场价 | $95.33 | $92.59 |'); inF('| 差额 | 0.84 | 1.44 |');
ok((D.q * 100).toFixed(2) === '1.43' && (N.q * 100).toFixed(2) === '6.17', '隐含违约概率 1.43% / 6.17%');
inF('| 价格里隐含的违约概率 | 1.43% | 6.17% |'); inF('| 隐含 ÷ 假设 | 约 14 倍 | 约 1.5 倍 |');
ok(Math.round(D.mult) === 14 && D.mult.toFixed(1) === '14.3' && N.mult.toFixed(1) === '1.5', '倍数 约 14 / 约 1.5');

// 第 4 节：两种年景
const good = 0.0005, bad = 0.0055;
ok(close(0.9 * good + 0.1 * bad, 0.001, 1e-15), '长期平均 0.10%');
inL('0.9 × 0.05% + 0.1 × 0.55% = 0.10%');
ok(close(1000 * good, 0.5) && close(1000 * bad, 5.5) && close(bad / good, 11, 1e-9), '1,000 家：0.5 家 / 5.5 家 / 11 倍');
inL('每年平均约有 0.5 家违约'); inL('平均约有 5.5 家违约，是好年景的 11 倍');
ok(close(good * LGD, 0.0003) && close(bad * LGD, 0.0033, 1e-15), '组合损失 0.03% / 0.33%');
inL('好年景的损失约是整个组合的 0.03%，坏年景约是 0.33%');
ok(close(0.9 * good * LGD + 0.1 * bad * LGD, 0.0006, 1e-15), '长期平均损失 0.06%'); inL('长期平均下来仍是每年 0.06%');

// 隐含违约概率的手算（课文用四舍五入后的价格）
ok(r2(95.33 * 1.04) === 99.14, '$95.33 × 1.04 ≈ $99.14'); inL('$95.33 × 1.04 ≈ $99.14');
ok((100 - 99.14).toFixed(2) === '0.86' && ((100 - 99.14) / 100 / LGD * 100).toFixed(2) === '1.43', '0.86% ÷ 60% ≈ 1.43%');
inL('平均损失 0.86%'); inL('得到约 1.43%');
inL('价格里隐含的却是 1.43%，约 14 倍');
const qN_hand = (1 - 92.59 * 1.04 / 100) / LGD;
ok((qN_hand * 100).toFixed(1) === '6.2' && (N.q * 100).toFixed(1) === '6.2', '北岭电池隐含违约概率约 6.2%（手算与精确一致到一位小数）');
inL('价格里隐含的违约概率约 6.2%，是假设的 4% 的约 1.5 倍');
inF('约 6.18%');
ok((qN_hand * 100).toFixed(2) === '6.18', '按 $92.59 手算 6.18%');
// 小题 1
inL('多出来的 0.84 个百分点'); inL('真实违约概率是每年 1.43%'); inL('平均违约损失约 0.06%');

// 第 3 节、图 2：Elton 等工作论文（1999）
const E = { A: { tot: 0.785, el: 0.140, elTax: 0.423 }, BBB: { tot: 1.180, el: 0.409, elTax: 0.683 } };
for (const [g, v] of Object.entries(E)) {
  v.tax = +(v.elTax - v.el).toFixed(3); v.rest = +(v.tot - v.elTax).toFixed(3);
  ok(close(v.el + v.tax + v.rest, v.tot, 1e-9), g + ' 三段之和等于实际利差');
}
ok(E.A.tax === 0.283 && E.A.rest === 0.362 && E.BBB.tax === 0.274 && E.BBB.rest === 0.497, '州税与其余部分');
ok(Math.round(E.A.el / E.A.tot * 100) === 18 && Math.round(E.BBB.el / E.BBB.tot * 100) === 35, '占比 约 18% / 约 35%');
inL('实际利差平均约 0.785 个百分点，其中预期违约损失只有约 0.140，约占 18%');
inL('BBB 级是 1.180 中的约 0.409，约占 35%');
inL('A 级 0.785、BBB 级 1.180 个百分点'); inL('A 级 0.140，BBB 级 0.409'); inL('A 级 0.283，BBB 级 0.274'); inL('A 级 0.362，BBB 级 0.497');
inF('| A | 0.785 | 0.140 | 0.283 | 0.362 |'); inF('| BBB | 1.180 | 0.409 | 0.274 | 0.497 |');
inF('A 级约 18%，BBB 级约 35%');
ok(E.A.tax > E.A.el && E.BBB.tax < E.BBB.el, 'A 级州税大于预期违约损失；BBB 级不是（课文只说 A 级和 AA 级）');
ok(0.335 - 0.048 > 0.048, 'AA 级（表 VII-B 0.335，表 VI 0.048）州税大于预期违约损失');
inL('A 级（见图 2）和 AA 级债券的利差中，州税的影响比预期违约损失还大');
inBoth('利差大约被高估 0.10 个百分点');
ok(close(0.10 * 0.05, 0.005, 1e-12), '州税例子：10% × 5% = 0.5 个百分点');
inL('票面利率 10%、有效州税率 5%，单是州税就相当于 0.5 个百分点的利差');
inL('有效州税率约为 4%');

// 旧金山联储 2010-06 与 Chen 等（经该文介绍）
inL('利差只应有约 0.22 个百分点'); inL('这类利差接近 1.60 个百分点'); inL('仍有约 1 个百分点需要解释');
ok(close(0.22 + 0.35, 0.57, 1e-12), '0.22 + 0.35 = 0.57');
inL('约 0.57 个百分点的利差，其中约 0.22 是预期损失，约 0.35 是风险补偿');

// Longstaff 等 NBER WP（2004）
inL('AAA 和 AA 级约 51%，A 级约 56%，BBB 级约 71%，BB 级约 83%');
ok(51 < 56 && 56 < 71 && 71 < 83, '违约部分占比随评级降低而上升');
inL('约为 0.20 到 1.00 个百分点'); inL('68 家公司'); inL('2001 年 3 月到 2002 年 10 月'); inL('只有 1% 到 2%');

// Feldhütter & Schaefer（2018）
inL('模型利差平均 1.11 个百分点，实际平均 0.92 个百分点');
ok(0.88 <= 0.92 && 0.92 <= 1.28, '实际 0.92 落在模型置信区间 0.88–1.28 内（原文 88–128 基点）');
ok(Math.floor(30 / 10) === 3, '30 年只够切成 3 段互不重叠的 10 年'); inL('只够切成 3 段互不重叠的 10 年');
inL('1987 年到 2012 年');

// Huang, Nozawa & Shi（2025）
inL('在 72 个评级、国家和参数组合里，有 53 个'); inL('8 个发达经济体'); inL('1997 年到 2017 年');
ok(53 / 72 > 0.5, '53/72 过半');

// 第 1 阶段第 5 课的 HQM 回顾
ok(close(+(5.92 - 5.13).toFixed(2), 0.79), 'HQM 5.92 − GS10 5.13 = 0.79');
inL('高约 0.79 个百分点');
inL('平均下来会损失 $0.60');
ok(close(100 * 0.01 * 0.6, 0.6), 'S01-05 算例 $0.60');

// 本课要点
inL('东川电力 0.1% × 60% = 0.06 个百分点，市场利差 0.90；北岭电池 4% × 60% = 2.40（精确 2.56），市场利差 4.00');

// 中国对照的日期
inL('2021 年 2 月 26 日'); inL('2022 年 8 月 6 日起施行'); inL('三个子级');

console.log(`通过 ${pass}，失败 ${fail}`);
if (fail) process.exit(1);
