// S02-05 数值核验：重算课文与图中的每个关键数字，并断言它确实出现在课文（或图与交互方案）里。
// 运行：node "lessons/S02-05/S02-05 数值核验.js"
// 不依赖网络与临时目录；只读同目录的《S02-05 课文 v1 候选.md》与《S02-05 图与交互方案 v1 候选.md》。
'use strict';
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const lesson = fs.readFileSync(path.join(dir, 'S02-05 课文 v1 候选.md'), 'utf8').replace(/\r/g, '');
const figs = fs.readFileSync(path.join(dir, 'S02-05 图与交互方案 v1 候选.md'), 'utf8').replace(/\r/g, '');

let pass = 0, fail = 0;
function ok(name, cond, note) {
  if (cond) pass++; else { fail++; console.log('✘ ' + name + (note ? '：' + note : '')); }
}
const r2 = x => Math.round(x * 100) / 100;
const money = x => {
  const neg = x < 0; const v = Math.abs(x);
  const s = (Number.isInteger(v) ? v.toLocaleString('en-US') : v.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 }));
  return (neg ? '−' : '') + '$' + s;
};
// 计算值 v 必须等于 expect（按两位小数），并且 text 里出现字符串 shown
function num(name, v, expect, shown, where) {
  const text = where === 'fig' ? figs : lesson;
  ok(name + ' 重算', Math.abs(r2(v) - expect) < 0.005, '算得 ' + v + '，应为 ' + expect);
  if (shown) ok(name + ' 出现在' + (where === 'fig' ? '图方案' : '课文'), text.includes(shown), '找不到「' + shown + '」');
}
const has = (name, s, where) => ok(name, (where === 'fig' ? figs : lesson).includes(s), '找不到「' + s + '」');

// ---------- 假设 ----------
const P0 = 50, N = 400, IM = 0.5, RATE = 0.08, DAYS = 30;
const SN = 200, SHORT_REQ = 1.5, FEE = 0.03, DIV = 0.25, MM_L = 0.25, MM_H = 0.30, MM_S = 0.30;
has('假设：400 股 @ $50', '借钱买了 400 股北岭电池，每股 $50');
has('假设：推演、实际仍是 600 股', '仍然只有前面几课那 600 股');
has('假设：8%', '假设年利率 8%');
has('假设：周岚 200 股', '决定卖空 200 股');
has('假设：季度股息 $0.25', '北岭电池每个季度派息，每股 $0.25');
has('假设：借券费 3%', '年费率 3%');

// ---------- 模型一：融资买入 ----------
const cost = N * P0, own = cost * IM, loan = cost - own;
num('买入总价', cost, 20000, '400 股 × $50 = $20,000');
num('自付 / 借款', own, 10000, '小林自己出 $10,000，向券商借 $10,000');
const interest = loan * RATE * DAYS / 365;
num('30 天利息', interest, 65.75, '$10,000 × 8% × 30 ÷ 365 ≈ $65.75');
num('初始权益', cost - loan, 10000, '$20,000 − $10,000 = $10,000');
const eq = p => N * p - loan;
num('$60 权益', eq(60), 14000, '权益 $14,000');
num('$60 杠杆收益率 %', (eq(60) / own - 1) * 100, 40, '多了 40%');
num('$60 全额现金收益率 %', (60 / P0 - 1) * 100, 20, '只多 20%');
num('$40 权益', eq(40), 6000, '权益只剩 $6,000');
num('$60 扣息收益率 %', ((eq(60) - interest) / own - 1) * 100, 39.34, '约 39.34%');
num('$40 扣息收益率 %', ((eq(40) - interest) / own - 1) * 100, -40.66, '约 40.66%');
num('全额买 200 股', own / P0, 200, '全额买 200 股');
num('一年利息', loan * RATE, 800, '一年的利息是 $800');
num('每股利息', loan * RATE / N, 2, '每股 $2');
num('利息打平价', P0 + loan * RATE / N, 52, '至少要涨到 $52');
const trig = m => loan / (N * (1 - m));
num('追缴线 25%', trig(MM_L), 33.33, '解出 P ≈ $33.33');
num('追缴线 30%', trig(MM_H), 35.71, '提高到约 $35.71');
ok('追缴线上权益恰等于要求', Math.abs(eq(trig(MM_L)) - MM_L * N * trig(MM_L)) < 1e-9);
const mv30 = N * 30, eq30 = eq(30), req30 = MM_L * mv30, call = req30 - eq30;
num('$30 市值', mv30, 12000, '股票值 $12,000');
num('$30 权益', eq30, 2000, '$12,000 − $10,000 = $2,000');
num('$30 要求', req30, 3000, '$12,000 × 25% = $3,000');
num('$30 追缴', call, 1000, '差 $1,000');
num('要卖的金额', call / MM_L, 4000, '$1,000 ÷ 25% = $4,000');
num('要卖的股数（未取整）', call / (MM_L * 30), 133.33, '133.3 股');
const sell = Math.ceil(call / (MM_L * 30));
num('要卖的股数', sell, 134, '要卖 134 股');
num('卖出金额', sell * 30, 4020, '共 $4,020');
const left = N - sell, debt2 = loan - sell * 30;
num('剩余股数', left, 266, '剩 266 股');
num('剩余市值', left * 30, 7980, '市值 $7,980');
num('剩余欠款', debt2, 5980, '欠款降到 $5,980');
num('卖后权益', left * 30 - debt2, 2000, '权益仍是 $2,000');
num('卖后要求', MM_L * left * 30, 1995, '维持要求是 $1,995');
ok('卖后满足要求', left * 30 - debt2 >= MM_L * left * 30);
ok('卖 133 股不够', (N - 133) * 30 - (loan - 133 * 30) < MM_L * (N - 133) * 30);
num('每卖 $1 要求降低', MM_L, 0.25, '只降低 25 美分');
num('权益归零价', loan / N, 25, '跌到 $25');
num('$15 倒欠', -eq(15), 4000, '还欠券商 $4,000');
num('$15 市值', N * 15, 6000, '股票只值 $6,000');

// ---------- 模型二：卖空 ----------
const proceeds = SN * P0, reqTotal = proceeds * SHORT_REQ, deposit = reqTotal - proceeds, credit = proceeds + deposit;
num('卖空所得', proceeds, 10000, '买方付 $10,000');
num('另交', deposit, 5000, '也就是 $5,000');
num('贷方余额', credit, 15000, '$10,000 + $5,000 = $15,000');
num('初始空头市值', SN * P0, 10000, '200 × $50 = $10,000');
num('初始权益', credit - SN * P0, 5000, '$15,000 − $10,000 = $5,000');
const fee = proceeds * FEE * DAYS / 365, pil = SN * DIV;
num('30 天借券费', fee, 24.66, '$10,000 × 3% × 30 ÷ 365 ≈ $24.66');
num('股息替代款', pil, 50, '200 × $0.25 = $50');
num('每涨 $1 空头市值增加', SN, 200, '空头市值就多 $200');
num('$5 规则与 30% 的分界价', 5 / MM_S, 16.67, '约 $16.67');
const strig = c => c / (SN * (1 + MM_S));
num('卖空追缴线', strig(credit), 57.69, '解出 P ≈ $57.69');
num('扣费后追缴线', strig(credit - fee - pil), 57.41, '约 $57.41');
ok('追缴线处 30% 高于每股 $5', MM_S * SN * strig(credit) > 5 * SN);
num('卖空追缴线离起点 %', (strig(credit) / P0 - 1) * 100, 15.38, null);
has('约 15% 的表述', '只比卖出价高了约 15%');
num('融资追缴线离起点（三分之一）', 1 - trig(MM_L) / P0, 0.33, null);
has('约三分之一的表述', '比买入价 $50 低了约三分之一');
const seq = p => credit - SN * p, sreq = p => Math.max(5 * SN, MM_S * SN * p);
num('$60 空头市值', SN * 60, 12000, '空头市值 $12,000');
num('$60 权益', seq(60), 3000, '$15,000 − $12,000 = $3,000');
num('$60 要求', sreq(60), 3600, '30% × $12,000 = $3,600');
const scall = sreq(60) - seq(60);
num('$60 追缴', scall, 600, '差 $600');
num('回补金额', scall / MM_S, 2000, '$600 ÷ 30% = $2,000');
num('回补股数（未取整）', scall / (MM_S * 60), 33.33, '33.3 股');
const cover = Math.ceil(scall / (MM_S * 60));
num('回补股数', cover, 34, '34 股、$2,040');
num('回补金额（整股）', cover * 60, 2040, '$2,040');
num('剩余空头', SN - cover, 166, '还欠 166 股');
num('回补后要求', MM_S * (SN - cover) * 60, 2988, '维持要求 $2,988');
num('回补后权益', (credit - cover * 60) - (SN - cover) * 60, 3000, '权益 $3,000，刚好够');
num('另交资金亏光价', credit / SN, 75, '股价涨到 $75');
num('$90 倒欠', -(seq(90)), 3000, '倒欠 $3,000');
num('$90 买回成本', SN * 90, 18000, '要 $18,000');
num('$40 买回成本', SN * 40, 8000, '花 $8,000');
num('$40 毛利', proceeds - SN * 40, 2000, '毛利 $2,000');
const net = proceeds - SN * 40 - fee - pil;
num('$40 净利', net, 1925.34, '净赚 $1,925.34');
num('$40 账户余额', credit - SN * 40 - fee - pil, 6925.34, '剩 $6,925.34');
num('$40 收益率 %', net / deposit * 100, 38.51, '约 38.51%');
num('$55 买回成本', SN * 55, 11000, '要花 $11,000');
num('$55 毛亏', SN * 55 - proceeds, 1000, '多付 $1,000');
num('两个账户起点权益比例 %', deposit / proceeds * 100, 50, '周岚的权益占空头市值的 50%');

// ---------- 回扣利率 ----------
const REF = 0.04;
num('容易借：回扣 %', (REF - 0.0025) * 100, 3.75, '出借方付给借券方 3.75%');
num('难借：回扣 %', (REF - 0.30) * 100, -26, '4% − 30% = −26%');
num('$1,000,000 30 天净付', 1000000 * 0.26 * 30 / 365, 21369.86, '约 $21,369.86');

// ---------- 中国对照 ----------
num('25% 维持保证金 ↔ 担保比例 %', 1 / (1 - MM_L) * 100, 133.33, '大约相当于 133% 的担保比例');
num('融资保证金比例 100% ↔ 自有占比 %', 1 / (1 + 1 / 1.0) * 100, 50, '和美国的 50% 相当');
['不低于 100%', '私募基金不低于 120%', '由 50% 提高到 80%', '原来的 130%', '跌 10% 以上', '2024 年 7 月 22 日', '2024 年 7 月 10 日'].forEach(s => has('中国对照：' + s, s));

// ---------- Piggly Wiggly（扫描图核过的数字） ----------
['前一天收在 72 美元', '一开盘就是 92½', '中午刚过到了 123', '约 5,000 股', '从 124 跌到了 95', '最高到 124，收在 82',
 '出价 100 美元买，有人要价 150 美元卖', '按每股 $150 结算，过时就是 $250', '超过 25,000 股', '20 万股流通 A 类股中除约 1,200 股以外',
 '把价格降到每股 $100', '只有 140 股', '8 月 13 日'].forEach(s => has('1923：' + s, s));
ok('1923：不用 105,000 / 103,000', !/10[35],000/.test(lesson));
ok('1923：不写交易所公告原话', !/交易所宣布/.test(lesson));
num('1923：五十多块（124 − 72）', 124 - 72, 52, '涨了五十多块');

// ---------- 图与交互方案中的数字 ----------
const figNums = ['$20,000', '$10,000', '$65.75', '$14,925.34', '$6,925.34', '$1,925.34', '$24.66', '$33.33', '$35.71', '$57.69', '$57.41', '$25', '$75'];
figNums.forEach(s => has('图方案含 ' + s, s, 'fig'));
// 静态表：融资
[[50, 20000, 10000, 5000], [40, 16000, 6000, 4000], [30, 12000, 2000, 3000], [25, 10000, 0, 2500], [15, 6000, -4000, 1500]].forEach(([p, mv, e, rq]) => {
  ok('图方案融资表 $' + p, r2(N * p) === mv && r2(eq(p)) === e && r2(MM_L * N * p) === rq);
  has('图方案融资表行 $' + p, '| $' + p + ' | ' + money(mv) + ' | ' + money(e) + ' | ' + money(rq) + ' |', 'fig');
});
has('图方案融资表追缴线行', '| $33.33 | $13,333.33 | $3,333.33 | $3,333.33 |', 'fig');
num('图方案追缴线市值', N * trig(MM_L), 13333.33, null);
// 静态表：卖空
[[40, 8000, 7000, 2400], [50, 10000, 5000, 3000], [55, 11000, 4000, 3300], [60, 12000, 3000, 3600], [75, 15000, 0, 4500], [90, 18000, -3000, 5400]].forEach(([p, mv, e, rq]) => {
  ok('图方案卖空表 $' + p, r2(SN * p) === mv && r2(seq(p)) === e && r2(sreq(p)) === rq);
  has('图方案卖空表行 $' + p, '| $' + p + ' | ' + money(mv) + ' | ' + money(e) + ' | ' + money(rq) + ' |', 'fig');
});
num('图方案卖空追缴线市值', SN * strig(credit), 11538.46, '| $57.69 | $11,538.46 | $3,461.54 | $3,461.54 |', 'fig');
num('图方案卖空追缴线权益', seq(strig(credit)), 3461.54, null);
num('图方案第 5 步余额', credit - fee - pil, 14925.34, '$14,925.34', 'fig');

console.log('通过 ' + pass + '，失败 ' + fail);
if (fail) process.exit(1);
