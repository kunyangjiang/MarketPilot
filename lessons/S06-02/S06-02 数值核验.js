// 文献与判决的数字：重算其中的差值、比值，并断言原值出现；原值出处见核验记录。
// 不依赖网络与临时目录。
'use strict';
const fs = require('fs');
const path = require('path');

const LESSON = fs.readFileSync(path.join(__dirname, 'S06-02 课文 v1 候选.md'), 'utf8').replace(/\r/g, '');
const FIG = fs.readFileSync(path.join(__dirname, 'S06-02 图与交互方案 v1 候选.md'), 'utf8').replace(/\r/g, '');

let pass = 0, fail = 0;
function ok(id, cond, msg) { if (cond) pass++; else { fail++; console.log('失败 ' + id + '：' + (msg || '')); } }
const near = (a, b, tol) => Math.abs(a - b) < (tol || 1e-9);
function num(id, got, want, dp, text, fig) {
  const r = Number(got.toFixed(dp));
  ok(id + ' 重算', near(r, want), `重算 ${got} → ${r}，应为 ${want}`);
  if (text) ok(id + ' 课文出现', LESSON.includes(text), `课文里没有「${text}」`);
  if (fig) ok(id + ' 图方案出现', FIG.includes(fig === true ? text : fig), `图方案里没有「${fig === true ? text : fig}」`);
}
const inL = (id, s) => ok(id + ' 课文出现', LESSON.includes(s), `课文里没有「${s}」`);
const inF = (id, s) => ok(id + ' 图方案出现', FIG.includes(s), `图方案里没有「${s}」`);

// ---------- A 组：文献、判决与新闻稿中的数字（原值出处见核验记录） ----------
inL('A1 诺奖日期', '2013 年 10 月 14 日');
inL('A2 新闻稿三到五年', '比如三到五年');
inL('A3 詹森样本', '1955 到 1964 年的 115 只共同基金');
inL('A4 詹森 89 只', '有 89 只落在市场线以下');
inL('A5 詹森 −14.6%', '平均少了约 14.6%');
ok('A6 89/115 超过四分之三', 89 / 115 > 0.75, String(89 / 115));
inL('A7 伊波利托样本', '1965 到 1984 年的 143 只共同基金');
inL('A8 伊波利托 +0.83%', '平均每年比市场线高 0.83%');
inL('A9 埃尔顿等 −1.1%', '平均每年 −1.1%');
num('A10 两种基准之差', 0.83 - (-1.1), 1.93, 2); // 同一批基金、同一时期，两把尺子相差约 1.93 个百分点/年
// 事件研究（Fama 1991 p.1601）：每日正常回报 ≈ 10% ÷ 250
num('A11 每日正常回报', 10 / 250, 0.04, 4, '只有约 0.04%');
num('A12 3 天正常回报', 3 * 10 / 250, 0.12, 4, '3 天的正常回报加起来约 0.12%');
inL('A13 并购 15%', '平均涨了 15% 以上');
ok('A14 估错一倍仍远小于 15%', 2 * 0.12 < 15 / 10, '0.24 应远小于 15');
inL('A15 每年 10% ÷ 250', '每年约 10% 除以 250 个交易日');
// 希勒 1981（p.433–434）
inL('A16 希勒五到十三倍', '五到十三倍');
inL('A17 希勒样本 1', '1871 到 1979 年的标准普尔综合指数');
inL('A18 希勒样本 2', '1928 到 1979 年的道琼斯工业股票');
// 判决
inL('A19 判决日期', '2014 年 6 月 23 日');
inL('A20 巴西克 1988', '1988 年的巴西克公司诉莱文森案');

// ---------- B 组：联合假设的教学例子（假设，参数沿用 S05-03） ----------
const rf = 4, mkt = 5, val = 3;
const capm = (bm) => rf + bm * mkt;
const two = (bm, bv) => rf + bm * mkt + bv * val;
num('B1 CAPM 正常回报', capm(1.0), 9, 4, '正常回报 = 4% + 1.0 × 5% = 9%', '4% + 1.0 × 5% = 9%');
num('B2 CAPM 异常回报', 11 - capm(1.0), 2, 4, '异常回报 = 11% − 9% = +2%', '异常回报 +2%');
num('B3 两因子 正常回报', two(1.0, 0.8), 11.4, 4, '正常回报 = 4% + 1.0 × 5% + 0.8 × 3% = 11.4%', '4% + 5% + 2.4% = 11.4%');
num('B4 两因子 异常回报', 11 - two(1.0, 0.8), -0.4, 4, '异常回报 = 11% − 11.4% = −0.4%', '异常回报 −0.4%');
num('B5 价值部分', 0.8 * val, 2.4, 4, '价值部分 2.4%', '（4%、5%、2.4%）');
inL('B6 要点', '按 CAPM 异常回报为 +2%，按两因子模型为 −0.4%');
// 小题 2
num('B7 小题2 CAPM', capm(1.2), 10, 4, '正常回报 4% + 1.2 × 5% = 10%，异常回报 0', '4% + 1.2 × 5% = 10%，异常 0');
num('B8 小题2 两因子', two(1.2, -0.3), 9.1, 4, '正常回报 4% + 6% − 0.3 × 3% = 9.1%', '4% + 6% − 0.9% = 9.1%');
num('B9 小题2 异常', 10 - two(1.2, -0.3), 0.9, 4, '异常回报 10% − 9.1% = +0.9%', '异常 +0.9%');
num('B10 小题2 干扰项 B', 10 - (rf + 1.2 * mkt + 0.3 * val), -0.9, 4, '两因子模型下为 −0.9%');
num('B11 小题2 干扰项 C', 10 - capm(1.0), 1, 4, 'CAPM 下为 +1%');

// ---------- C 组：信息成本悖论的教学模型 ----------
// 每人分到 (A − b n) ÷ n；均衡 (A − b n)/n = c → n* = A/(b + c)；价格吸收 = b n*/A = b/(b + c)
const b = 2;
const share = (A, n) => (A - b * n) / n;
const nStar = (A, c) => A / (b + c);
function nSearch(A, c) { // 独立办法：逐人进场，直到下一位进场后每人分到的钱低于成本
  let n = 0;
  while (n + 1 <= A / b && share(A, n + 1) >= c - 1e-12) n++;
  return n;
}
const absorbed = (A, n) => b * n / A;
num('C1 n=10 每人', share(120, 10), 10, 4, '10 人时，每人 10 万元');
num('C2 n=40 每人', share(120, 40), 1, 4, '40 人时，每人 1 万元');
num('C3 n=30 每人', share(120, 30), 2, 4, '每人（120 − 60）÷ 30 = 2 万元');
num('C4 均衡 c=2 封闭解', nStar(120, 2), 30, 6, '所以均衡在 30 人');
num('C5 均衡 c=2 逐人搜索', nSearch(120, 2), 30, 0);
num('C6 c=2 剩余利润', 120 - b * 30, 60, 4, '利润从 120 万元缩到 60 万元');
num('C7 c=2 吸收', absorbed(120, 30), 0.5, 6, '价格吸收了一半的信息');
num('C8 c=4 均衡', nStar(120, 4), 20, 6, '得 n = 20');
num('C9 c=4 搜索', nSearch(120, 4), 20, 0);
num('C10 c=4 吸收', absorbed(120, 20), 0.333333, 6, '价格只吸收三分之一的信息');
num('C11 c=1 均衡', nStar(120, 1), 40, 6, '每人 1 万元：n = 40');
num('C12 c=1 搜索', nSearch(120, 1), 40, 0);
num('C13 c=1 吸收', absorbed(120, 40), 0.666667, 6, '价格吸收三分之二');
num('C14 全部吸收人数', 120 / b, 60, 6, '到 60 人都在研究时');
num('C15 噪声 全部吸收人数', 180 / b, 90, 6, '到 90 人时才全部吸收');
num('C16 噪声 均衡', nStar(180, 2), 45, 6, 'n = 45');
num('C17 噪声 搜索', nSearch(180, 2), 45, 0);
num('C18 噪声 吸收不变', absorbed(180, 45), 0.5, 6, '价格吸收的仍是一半');
ok('C19 吸收比例与 A 无关', near(absorbed(120, nStar(120, 2)), absorbed(180, nStar(180, 2))), '噪声变多时吸收比例应不变');
// 成本趋于零：n* → 60，吸收 → 1，每人收入 → 0
num('C20 c→0 均衡', nStar(120, 1e-9), 60, 6);
num('C21 c→0 吸收', absorbed(120, nStar(120, 1e-9)), 1, 6);
ok('C22 只要 c>0 吸收 <1', [0.01, 0.1, 1, 2, 4].every(c => absorbed(120, nStar(120, c)) < 1), '');
ok('C23 潜在研究者 100 人足够', nStar(180, 2) <= 100 && nStar(120, 1) <= 100, '');
inL('C24 100 位', '有 100 位潜在的研究者');
// 小题 3
num('C25 小题3 均衡', nStar(120, 3), 24, 6, 'n = 24');
num('C26 小题3 搜索', nSearch(120, 3), 24, 0);
num('C27 小题3 缩掉', b * 24, 48, 4, '利润缩掉 2 × 24 = 48 万元');
num('C28 小题3 吸收', absorbed(120, 24) * 100, 40, 6, '占 120 万元的 40%');
inL('C29 小题3 120 = 5n', '即 120 = 5n');
// 图方案
inF('C30 图 3 c=1', 'c = 1：n* = 40，吸收 2/3（约 67%）');
inF('C31 图 3 c=2', 'c = 2：n* = 30，吸收 1/2');
inF('C32 图 3 c=4', 'c = 4：n* = 20，吸收 1/3（约 33%）');
inF('C33 图 3 噪声', 'A = 180，c = 2：n* = 45，吸收 1/2');
inF('C34 图 3 小题', 'c = 3，n* = 24，吸收 40%');
inL('C35 要点', '均衡的知情交易者为 40、30、20 人');

// ---------- D 组：「难以预测」的教学模型 ----------
const m0 = 20, keep = 0.98, sig = 5;
const corr = (t) => m0 * (1 - Math.pow(keep, t)); // t 个月后预期修正（百分点）
// 独立办法：逐月递推预期偏离
function corrIter(t) { let m = m0; for (let i = 0; i < t; i++) m *= keep; return m0 - m; }
num('D1 1 个月修正', corr(1), 0.4, 6, '20% × 2% = 0.4 个百分点');
num('D2 1 个月 递推', corrIter(1), 0.4, 6);
num('D3 比值', sig / corr(1), 12.5, 6, '是它的 12 倍多');
ok('D4 「12 倍多」成立', sig / corr(1) > 12 && sig / corr(1) < 13, String(sig / corr(1)));
num('D5 1 年修正', corr(12), 4.3, 1, '约 4.3 个百分点', '≈ 4.3 个百分点');
num('D6 1 年 递推', corrIter(12), 4.3, 1);
num('D7 5 年修正', corr(60), 14.0, 1, '约 14 个百分点', '≈ 14.0 个百分点');
num('D8 5 年 递推', corrIter(60), 14.0, 1);
num('D9 1 年随机', sig * Math.sqrt(12), 17.3, 1, null, '5% × √12 ≈ 17.3%');
num('D10 5 年随机', sig * Math.sqrt(60), 38.7, 1, '五年约 38.7%', '5% × √60 ≈ 38.7%');
// 模拟复核：许多条路径的平均月度修正与随机部分（固定种子，确定性）
let seed = 20261120;
const rnd = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };
const gauss = () => { const u = Math.max(rnd(), 1e-12), v = rnd(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v); };
let sumCorr = 0, sumSq = 0; const N = 20000;
for (let k = 0; k < N; k++) { let m = m0, cum = 0; for (let t = 0; t < 60; t++) { const e = sig * gauss(); cum += e; m *= keep; } sumCorr += m0 - m; sumSq += cum * cum; }
num('D11 模拟 5 年修正', sumCorr / N, 14.0, 1);
ok('D12 模拟 5 年随机≈38.7', Math.abs(Math.sqrt(sumSq / N) - 38.7) < 1.0, String(Math.sqrt(sumSq / N)));
inL('D13 20%', '比它的真实价值高 20%');
inL('D14 保留 98%', '也就是保留 98%');
inL('D15 5% 波动', '约 5% 的随机上下波动');
inL('D16 要点', '下个月可预测的修正只有 0.4 个百分点，是随机波动的十几分之一');
inF('D17 图 4 参数', '偏离每月保留 98%');

console.log(`通过 ${pass}，失败 ${fail}`);
if (fail) process.exit(1);
