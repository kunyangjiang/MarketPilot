// ---------- D 组：固定种子的蒙特卡洛，独立复算封闭解 ----------
// 构造：误差_i = σ × (√ρ × Z + √(1−ρ) × e_i)，Z 为共同因子，e_i 为个人因子，均为标准正态；
// 价格偏离 = 平均误差。重复多次，取标准差，与封闭解比较（相对误差 5% 以内）。
function rng(seed) { let s = seed >>> 0; return () => { s = (s + 0x6D2B79F5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
function normal(r) { let u = 0; while (u === 0) u = r(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * r()); }
function simulate(N, rho, reps, seed) {
  const r = rng(seed); let s2 = 0;
  for (let k = 0; k < reps; k++) {
    const Z = normal(r); let sum = 0;
    for (let i = 0; i < N; i++) sum += SIG * (Math.sqrt(rho) * Z + Math.sqrt(1 - rho) * normal(r));
    const m = sum / N; s2 += m * m;
  }
  return Math.sqrt(s2 / reps);
}
for (const [rho, seed] of [[0, 20261120], [0.1, 20261121]]) {
  const sim = simulate(1000, rho, 4000, seed), exact = dev(1000, rho);
  ok(`D 蒙特卡洛 N=1000 ρ=${rho}`, Math.abs(sim / exact - 1) < 0.05, `模拟 ${sim.toFixed(4)}，封闭解 ${exact.toFixed(4)}`);
}
