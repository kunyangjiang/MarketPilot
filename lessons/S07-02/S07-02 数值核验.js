// ---------- 通用：p-选美比赛 ----------
// 胜者：离 p × 平均数最近的人（并列平分）。返回每人的奖金份额。
function payoffs(xs, p) {
  const t = p * xs.reduce((a, b) => a + b, 0) / xs.length;
  const d = xs.map(x => Math.abs(x - t));
  const m = Math.min(...d);
  const win = d.map(v => near(v, m, 1e-12));
  const k = win.filter(Boolean).length;
  return win.map(w => (w ? 1 / k : 0));
}
// 「人人写 v」是否均衡：任何一人单独改成网格上任一数，奖金份额都不会增加
function isSymEq(v, p, n, grid, cont) {
  const base = payoffs(Array(n).fill(v), p)[0];
  // cont = true：允许写任意小数，另加 v 附近与 v 以下的细分偏离（v × j/100）
  const devs = cont ? grid.concat(Array.from({ length: 200 }, (_, j) => v * j / 100)) : grid;
  for (const y of devs) {
    if (y < 0 || y > 100) continue;
    if (near(y, v)) continue;
    const xs = Array(n).fill(v); xs[0] = y;
    if (payoffs(xs, p)[0] > base + 1e-12) return false;
  }
  return true;
}
