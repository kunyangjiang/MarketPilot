// ---------- E 组：收益表与马勒布（2014）例子（S0702-R04） ----------
// 2×2 博弈的纯策略均衡：返回 [i,j] 列表；A[i][j] = 行玩家收益，B[i][j] = 列玩家收益
function pureNE(A, B) {
  const out = [];
  for (let i = 0; i < 2; i++) for (let j = 0; j < 2; j++)
    if (A[i][j] >= A[1 - i][j] && B[i][j] >= B[i][1 - j]) out.push([i, j]);
  return out.map(x => x.join(''));
}
